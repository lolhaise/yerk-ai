# the schedule: cron, every, at
MONTHS = {m: i + 1 for i, m in enumerate(("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov",
                                          "dec"))}
DAYS = {d: i for i, d in enumerate(("sun", "mon", "tue", "wed", "thu", "fri", "sat"))}
DAY_NAMES = ("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")


def _num(text: str, names: dict[str, int], lo: int, hi: int) -> int:
    key = text.strip().lower()[:3]
    if names and key in names and not text.strip().isdigit():
        n = names[key]
    else:
        try:
            n = int(text)
        except ValueError:
            raise JobError(f"{text!r} is not a number") from None
    if not lo <= n <= hi:
        raise JobError(f"{n} is outside {lo}-{hi}")
    return n


def _field(text: str, lo: int, hi: int, names: dict[str, int] | None = None) -> set[int]:
    names = names or {}
    out: set[int] = set()
    for part in text.split(","):
        step = 1
        if "/" in part:
            part, s = part.split("/", 1)
            step = _num(s, {}, 1, hi)
        if part == "*":
            a, b = lo, hi
        elif "-" in part:
            x, y = part.split("-", 1)
            a, b = _num(x, names, lo, hi), _num(y, names, lo, hi)
            if a > b:
                raise JobError(f"the range {part!r} runs backwards")
        else:
            a = _num(part, names, lo, hi)
            b = hi if step > 1 else a
        out.update(range(a, b + 1, step))
    return out


def _compact(values: set[int], lo: int, hi: int) -> str:
    """A set as systemd writes it: "*" for all, "lo/step" for a stride from lo, else the list."""
    s = sorted(values)
    if s == list(range(lo, hi + 1)):
        return "*"
    for step in range(2, hi - lo + 1):
        if len(s) >= 3 and s == list(range(lo, hi + 1, step)):
            return f"{lo}/{step}"
    return ",".join(map(str, s))


@dataclass(frozen=True)
class Cron:
    minute: frozenset[int]
    hour: frozenset[int]
    dom: frozenset[int]
    month: frozenset[int]
    dow: frozenset[int]
    dom_any: bool
    dow_any: bool

    @classmethod
    def parse(cls, expr: str) -> Cron:
        parts = expr.split()
        if len(parts) != 5:
            raise JobError(f"a cron expression has five fields (minute hour day month weekday), this has {len(parts)}")
        try:
            minute, hour = _field(parts[0], 0, 59), _field(parts[1], 0, 23)
            dom, month = _field(parts[2], 1, 31), _field(parts[3], 1, 12, MONTHS)
            dow = {d % 7 for d in _field(parts[4], 0, 7, DAYS)}
        except JobError as e:
            raise JobError(f"in the cron expression {expr!r}: {e}") from None
        return cls(frozenset(minute), frozenset(hour), frozenset(dom), frozenset(month), frozenset(dow),
                   parts[2] == "*", parts[4] == "*")

    def day_ok(self, d: date) -> bool:
        if d.month not in self.month:
            return False
        dom, dow = d.day in self.dom, (d.isoweekday() % 7) in self.dow
        if self.dom_any and self.dow_any:
            return True
        if self.dom_any:
            return dow
        if self.dow_any:
            return dom
        return dom or dow                  # vixie cron: when both are restricted, either one matches

    def _times(self, d: date, tz: ZoneInfo, reverse: bool = False) -> Iterator[datetime]:
        for h in sorted(self.hour, reverse=reverse):
            for m in sorted(self.minute, reverse=reverse):
                t = datetime(d.year, d.month, d.day, h, m, tzinfo=tz)
                if t.astimezone(timezone.utc).astimezone(tz).replace(tzinfo=None) == t.replace(tzinfo=None):
                    yield t                # a wall time the zone skips (a spring-forward gap) is not a fire

    def next(self, after: float, tz: ZoneInfo) -> float:
        start = datetime.fromtimestamp(after, tz).date()
        for i in range(366 * 5):
            d = start + timedelta(days=i)
            if self.day_ok(d):
                for t in self._times(d, tz):
                    if t.timestamp() > after:
                        return t.timestamp()
        raise JobError("no fire time in the next five years")

    def prev(self, before: float, tz: ZoneInfo) -> float | None:
        start = datetime.fromtimestamp(before, tz).date()
        for i in range(366 * 5):
            d = start - timedelta(days=i)
            if self.day_ok(d):
                for t in self._times(d, tz, reverse=True):
                    if t.timestamp() <= before:
                        return t.timestamp()
        return None

    def calendar(self, tz: str) -> list[str]:
        """OnCalendar= lines: two when both the day of month and the weekday are restricted, since
        cron fires on either and systemd on both."""
        clock = f"{_compact(set(self.hour), 0, 23)}:{_compact(set(self.minute), 0, 59)}:00 {tz}"
        months = _compact(set(self.month), 1, 12)
        dows = ",".join(DAY_NAMES[d] for d in sorted(self.dow))
        doms = _compact(set(self.dom), 1, 31)
        if self.dom_any and self.dow_any:
            return [f"*-{months}-* {clock}"]
        out = []
        if not self.dow_any:
            out.append(f"{dows} *-{months}-* {clock}")
        if not self.dom_any:
            out.append(f"*-{months}-{doms} {clock}")
        return out


DURATION = re.compile(r"(\d+)\s*(d|days?|h|hours?|hrs?|m|min|mins|minutes?|s|secs?|seconds?)(?![a-z])", re.I)
UNITS_S = {"d": 86400, "h": 3600, "m": 60, "s": 1}


def parse_every(text: str) -> int:
    """A duration in seconds: "30m", "2h", "1h30m", "90s", "2 hours"."""
    t = text.strip().lower().removeprefix("every").strip()
    found = DURATION.findall(t)
    if not found or DURATION.sub("", t).strip(" ,"):
        raise JobError(f"{text!r} is not a duration (write it like 30m, 2h, 1h30m or 90s)")
    secs = sum(int(n) * UNITS_S[u[0]] for n, u in found)
    if secs < MIN_EVERY:
        raise JobError(f"every {text!r} is under {MIN_EVERY} seconds; that close together is a watcher's job")
    return secs


def every_cron(seconds: int) -> str | None:
    """An interval that divides an hour or a day, as the cron expression of its clock boundaries;
    None for the rest (those run on systemd's monotonic clock from the sync)."""
    if seconds % 60:
        return None
    m = seconds // 60
    if m < 60 and 60 % m == 0:
        return f"*/{m} * * * *" if m > 1 else "* * * * *"
    if m % 60 == 0:
        h = m // 60
        if h < 24 and 24 % h == 0:
            return f"0 */{h} * * *" if h > 1 else "0 * * * *"
        if h == 24:
            return "0 0 * * *"
    return None


def parse_at(value: Any, tz: ZoneInfo | None) -> float:
    """One time as an epoch: a TOML datetime or an ISO string; naive ones are read in `tz`."""
    if isinstance(value, datetime):
        dt = value
    elif isinstance(value, str):
        try:
            dt = datetime.fromisoformat(value.strip().replace(" ", "T", 1) if "T" not in value else value.strip())
        except ValueError:
            raise JobError(f"{value!r} is not a date and time (write it like 2026-03-09 09:00)") from None
    else:
        raise JobError("`at` must be a date and time")
    if dt.tzinfo is None:
        if tz is None:
            raise JobError("`at` has no offset, so it needs `tz` (an IANA name such as Europe/Paris)")
        dt = dt.replace(tzinfo=tz)
    return dt.timestamp()


def zone(name: str) -> ZoneInfo:
    try:
        return ZoneInfo(name)
    except (ZoneInfoNotFoundError, ValueError, TypeError):
        raise JobError(f"{name!r} is not a time zone name (an IANA name such as Europe/Paris or Asia/Tokyo)") from None


# the job
@dataclass(frozen=True)
class Job:
    name: str
    kind: str
    room: str
    when: str                     # "cron", "every" or "at"
    spec: str                     # the cron expression, the duration, or the time as written
    tz: str                       # IANA name ("" only for `every` with none given)
    cap: float                    # minutes
    deliver: str
    payload: str                  # the command or the message
    account: str = ""
    every_seconds: int = 0
    at_epoch: float = 0.0
    match: str = ""               # a watcher's prefix, or its regex when `regex`
    regex: bool = False
    batch: float = 10.0
    lines: int = 20
    wake: str = "room"
    prime: float = 5.0
    ask: str = ""                 # a watcher's optional message: what to do with the lines

    @property
    def unit(self) -> str:
        return f"{UNIT}{self.name}"

    @property
    def zone(self) -> ZoneInfo:
        return ZoneInfo(self.tz or "UTC")

    def describe(self) -> str:
        if self.kind == "watcher":
            return f"watcher on {'regex' if self.regex else 'prefix'} {self.match!r}, wakes the {self.wake}"
        if self.when == "cron":
            return f"cron `{self.spec}` {self.tz}"
        if self.when == "every":
            return f"every {self.spec}"
        return f"one-shot {when_text(self.at_epoch, self.tz)}"

    @property
    def cron(self) -> Cron | None:
        """The clock expression behind a cron schedule, or behind an interval that divides an hour
        or a day; None for a one-shot or an interval that runs on the monotonic clock."""
        if self.when == "cron":
            return Cron.parse(self.spec)
        if self.when == "every" and (expr := every_cron(self.every_seconds)):
            return Cron.parse(expr)
        return None

    def next_fire(self, now: float, last: float | None = None) -> float | None:
        """What the schedule says comes next (systemd's own answer is the one shown; this is for
        the plan, the planned time and the tests)."""
        if self.cron is not None:
            return self.cron.next(now, self.zone)
        if self.when == "every":
            return (last if last else now) + self.every_seconds
        return self.at_epoch if self.at_epoch > now else None

    def planned(self, fired: float, last_trigger: float | None = None) -> float:
        """The time this run was meant for: the clock instant at or before the fire, the one-shot's
        time, or for a monotonic interval the timer's own trigger time."""
        if self.cron is not None:
            return self.cron.prev(fired, self.zone) or fired
        if self.when == "at":
            return self.at_epoch
        return last_trigger if last_trigger and abs(fired - last_trigger) < 3600 else fired

    def calendar(self) -> list[str]:
        """OnCalendar= lines; [] for an interval on the monotonic clock."""
        if self.kind == "watcher":
            return []
        if self.cron is not None:
            return self.cron.calendar(self.tz or "UTC")
        if self.when == "at":
            return [datetime.fromtimestamp(self.at_epoch, self.zone).strftime("%Y-%m-%d %H:%M:%S") + f" {self.tz}"]
        return []


def make_job(name: str, raw: dict[str, Any], now: float | None = None) -> Job:
    """One [jobs.NAME] table checked against KEYS; a JobError says what is wrong."""
    now = time.time() if now is None else now
    if not isinstance(name, str) or not NAME.match(name):
        raise JobError("the name must be lowercase letters, digits and hyphens, starting with a letter or digit, "
                       "at most 60 characters")
    bad = sorted(set(raw) - set(KEYS))
    if bad:
        raise JobError(f"unknown key{'s' if len(bad) > 1 else ''} {', '.join(bad)}; the keys are {', '.join(KEYS)}")
    kind = str(raw.get("kind", ""))
    if kind not in KINDS:
        raise JobError(f'`kind` must be "script", "agent" or "watcher"' + (f", not {kind!r}" if kind else ""))
    if kind == "watcher":
        return make_watcher(name, raw)
    for k in ("prefix", "regex", "batch", "lines", "wake", "prime"):
        if k in raw:
            raise JobError(f"`{k}` is for watchers; this is a{'n' if kind == 'agent' else ''} {kind} job")
    whens = [k for k in ("schedule", "every", "at") if k in raw]
    if len(whens) != 1:
        raise JobError("give exactly one of `schedule` (cron), `every` (a duration) or `at` (one time)")
    when = {"schedule": "cron", "every": "every", "at": "at"}[whens[0]]
    tz_name = str(raw.get("tz", "") or "")
    tz = zone(tz_name) if tz_name else None
    if when == "cron" and tz is None:
        raise JobError("`schedule` needs `tz` (an IANA name such as Europe/Paris), so the hours mean what you mean")
    room = str(raw.get("room", "") or "")
    if not room:
        raise JobError("`room` is required: the room the output or the relay lands in")
    try:
        cap = float(raw.get("cap", DEFAULT_CAP[kind]))
    except (TypeError, ValueError):
        raise JobError("`cap` must be a number of minutes") from None
    if not cap > 0:
        raise JobError("`cap` must be above 0 minutes")
    deliver = str(raw.get("deliver", "announce"))
    if deliver not in DELIVER:
        raise JobError('`deliver` must be "announce" or "silent"')
    account = str(raw.get("account", "") or "")
    if kind == "script":
        if "message" in raw:
            raise JobError("a script job has `command`, not `message`")
        if account:
            raise JobError("a script job runs with no account; `account` is for agent jobs")
        payload = str(raw.get("command", "") or "")
        if not payload.strip():
            raise JobError("a script job needs `command`, the shell line to run")
    else:
        if "command" in raw:
            raise JobError("an agent job has `message`, not `command`")
        payload = str(raw.get("message", "") or "")
        if not payload.strip():
            raise JobError("an agent job needs `message`, the brief its worker gets")
    every_s, at_epoch, spec = 0, 0.0, ""
    if when == "cron":
        spec = str(raw["schedule"])
        Cron.parse(spec)
    elif when == "every":
        spec = str(raw["every"])
        every_s = parse_every(spec)
    else:
        at_epoch = parse_at(raw["at"], tz)
        shown = datetime.fromtimestamp(at_epoch, tz or timezone.utc)
        spec = shown.isoformat(timespec="minutes")
        if tz is None:
            tz_name = "UTC"
        if at_epoch <= now:
            raise JobError(f"`at` {when_text(at_epoch, tz_name)} is in the past")
    return Job(name, kind, room, when, spec, tz_name, cap, deliver, payload, account, every_s, at_epoch)


def make_watcher(name: str, raw: dict[str, Any]) -> Job:
    """A watcher: a command that runs all the time, no schedule; its matching lines are events."""
    if any(k in raw for k in ("schedule", "every", "at")):
        raise JobError("a watcher runs all the time: no `schedule`, `every` or `at`")
    room = str(raw.get("room", "") or "")
    if not room:
        raise JobError("`room` is required: the room the events wake")
    command = str(raw.get("command", "") or "")
    if not command.strip():
        raise JobError("a watcher needs `command`, the shell line whose output it watches")
    if ("prefix" in raw) == ("regex" in raw):
        raise JobError("give exactly one of `prefix` (a line that starts with it is an event) or `regex`")
    match, regex = str(raw.get("prefix", raw.get("regex", ""))), "regex" in raw
    if not match:
        raise JobError("the prefix or the regex cannot be empty")
    if regex:
        try:
            re.compile(match)
        except re.error as e:
            raise JobError(f"`regex` does not compile: {e}") from None
    wake = str(raw.get("wake", "room"))
    if wake not in WAKES:
        raise JobError('`wake` must be "room" or "worker"')
    account = str(raw.get("account", "") or "")
    if account and wake != "worker":
        raise JobError('`account` is for a watcher that wakes a worker (wake = "worker")')
    try:
        cap, batch = float(raw.get("cap", DEFAULT_CAP["watcher"])), float(raw.get("batch", 10))
        lines, prime = int(raw.get("lines", 20)), float(raw.get("prime", 5))
    except (TypeError, ValueError):
        raise JobError("`cap`, `batch`, `lines` and `prime` are numbers") from None
    if not cap > 0 or batch < 0 or lines < 1 or prime < 0:
        raise JobError("`cap` is above 0 minutes, `batch` and `prime` 0 seconds or more, `lines` at least 1")
    deliver = str(raw.get("deliver", "announce"))
    if deliver not in DELIVER:
        raise JobError('`deliver` must be "announce" or "silent"')
    tz = str(raw.get("tz", "") or "")
    if tz:
        zone(tz)
    return Job(name, "watcher", room, "watch", "", tz, cap, deliver, command, account, match=match, regex=regex,
               batch=batch, lines=lines, wake=wake, prime=prime, ask=str(raw.get("message", "") or ""))


def load(path: Path, now: float | None = None) -> tuple[dict[str, Job], dict[str, str]]:
    """Every job in the file, and for each one that cannot be scheduled, why."""
    if not path.is_file():
        return {}, {}
    try:
        data = tomllib.loads(path.read_text())
    except (tomllib.TOMLDecodeError, OSError) as e:
        return {}, {"(file)": f"{path} does not parse: {e}"}
    jobs, errors = {}, {}
    table = data.get("jobs", {})
    if not isinstance(table, dict):
        return {}, {"(file)": f"{path}: [jobs] must be a table of tables"}
    for name, raw in table.items():
        try:
            if not isinstance(raw, dict):
                raise JobError("a job is a table: [jobs.NAME] with its keys below it")
            jobs[str(name)] = make_job(str(name), raw, now)
        except JobError as e:
            errors[str(name)] = str(e)
    return jobs, errors


def when_text(epoch: float | None, tz: str) -> str:
    if epoch is None:
        return "never"
    return datetime.fromtimestamp(epoch, ZoneInfo(tz or "UTC")).strftime("%a %Y-%m-%d %H:%M:%S %Z")


def in_text(epoch: float | None, now: float) -> str:
    if epoch is None:
        return ""
    d = epoch - now
    return f"in {took(d)}" if d >= 0 else f"{took(-d)} ago"


# the file: append a job, remove a job, under a lock
@contextmanager
def locked(path: Path) -> Iterator[None]:
    lock = path.with_name(f".{path.name}.lock")
    with open(lock, "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


def _toml_value(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return f"{v:g}" if isinstance(v, float) else str(v)
    return json.dumps(str(v), ensure_ascii=False)


def block(name: str, fields: dict[str, Any]) -> str:
    """A [jobs.NAME] table as text, keys in KEYS order."""
    lines = [f"[jobs.{name}]"]
    lines += [f"{k} = {_toml_value(fields[k])}" for k in KEYS if k in fields and fields[k] not in ("", None)]
    return "\n".join(lines) + "\n"


def _span(text: str, name: str) -> tuple[int, int] | None:
    """Where [jobs.NAME] sits in the file: its header line through the blank lines before the next
    table; for the last table, the blank lines before it go too, so the file ends cleanly."""
    m = re.search(rf"^\[jobs\.{re.escape(name)}\][ \t]*(#[^\n]*)?\n", text, re.M)
    if not m:
        return None
    nxt = re.search(r"^\[", text[m.end():], re.M)
    start = m.start()
    if nxt:
        return start, m.end() + nxt.start()
    while start > 0 and text[start - 1] == "\n" and (start < 2 or text[start - 2] == "\n"):
        start -= 1
    return start, len(text)


def add(path: Path, name: str, fields: dict[str, Any], now: float | None = None) -> Job:
    """Append one job to the file (made first, so a bad one never lands); the rest of the file is
    untouched, comments included."""
    job = make_job(name, fields, now)
    with locked(path):
        text = path.read_text() if path.is_file() else ""
        if _span(text, name):
            raise JobError(f"a job named {name!r} is already in the file; remove it first, or pick another name")
        if text and not text.endswith("\n"):
            text += "\n"
        path.write_text(text + ("\n" if text.strip() else "") + block(name, fields))
    return job


def remove(path: Path, name: str) -> bool:
    """Drop [jobs.NAME] from the file; False when it is not there."""
    with locked(path):
        text = path.read_text() if path.is_file() else ""
        span = _span(text, name)
        if span is None:
            return False
        path.write_text(text[:span[0]] + text[span[1]:])
    return True


def fields_for(kind: str, when: str, what: str, room: str, tz: str, deliver: str = "announce", cap: float = 0.0,
               account: str = "") -> dict[str, Any]:
    """The table a `schedule add` writes: `when` is a time (a one-shot), "every ..." (an interval)
    or a cron expression; `what` is the message (agent) or the command (script)."""
    w = when.strip()
    out: dict[str, Any] = {"kind": kind, "room": room}
    if re.match(r"^\d{4}-\d{2}-\d{2}", w):
        out["at"] = w
    elif w.lower().startswith("every ") or (DURATION.fullmatch(w) and len(w.split()) == 1):
        out["every"] = w.lower().removeprefix("every").strip()
    else:
        out["schedule"] = w
    if tz:
        out["tz"] = tz
    if cap:
        out["cap"] = cap
    if deliver != "announce":
        out["deliver"] = deliver
    if account:
        out["account"] = account
    out["command" if kind == "script" else "message"] = what
    return out


def default_tz(room_confs: dict[str, dict[str, Any]], room: str, conf: dict[str, Any]) -> str:
    """The zone a job gets when the call names none: the room's `timezone`, else [memory] timezone
    in yerkd.toml; "" when neither exists (the job is then refused, never put on UTC by accident)."""
    return str(room_confs.get(room, {}).get("timezone") or conf.get("memory", {}).get("timezone") or "")


