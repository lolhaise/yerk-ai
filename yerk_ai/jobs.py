class JobError(ValueError):
    """Why a job cannot be scheduled, in one sentence."""


# the schedule: a calendar line, or one time
DAY_NAMES = ("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")
DURATION = re.compile(r"(\d+)\s*(d|days?|h|hours?|hrs?|m|min|mins|minutes?|s|secs?|seconds?)(?![a-z])", re.I)   # location.py's
UNITS_S = {"d": 86400, "h": 3600, "m": 60, "s": 1}


def cron_refusal(spec: str) -> str:
    """The one line that refuses a cron line (five fields, no colon) in `schedule`, with the calendar line that says the same when
    this can say it exactly (numbers, `*`, lists, ranges, a `*/n` step; one of the two day fields; no weekday range from Sunday,
    which ends systemd's week); "" for any other schedule. The loader raises it, `yerk doctor` prints it: the jobs file is the owner's, never rewritten."""
    if len(f := spec.split()) != 5 or ":" in spec:
        return ""
    head = f"`schedule` takes a systemd calendar line now, not cron: replace schedule = {toml_value(spec)} with "
    if "*" not in (f[2], f[4]) or not re.fullmatch(r"\*|([0-7]|[1-6]-[1-7])(,([0-7]|[1-6]-[1-7]))*", f[4]) or not all(
            re.fullmatch(r"\*(/\d+)?|\d+(-\d+)?(,\d+(-\d+)?)*", x) for x in f[:4]):
        return head + 'a calendar line (`man systemd.time`; "Mon 10:00" is Mondays at 10)'
    minute, hour, dom, month = (x.replace("-", "..").replace("*/", "0/" if i < 2 else "1/") for i, x in enumerate(f[:4]))
    days = "" if f[4] == "*" else ",".join("..".join(DAY_NAMES[int(d) % 7] for d in r.split("-")) for r in f[4].split(",")) + " "
    return head + f"schedule = {toml_value(f'{days}*-{month}-{dom} {hour}:{minute}:00')}"


def parse_at(value: Any, tz: ZoneInfo | None) -> float:
    """One time as an epoch: a TOML datetime or an ISO string; naive ones are read in `tz`."""
    if isinstance(value, datetime):
        dt = value
    elif isinstance(value, str):
        try:
            dt = datetime.fromisoformat(value.strip().replace(" ", "T", 1) if "T" not in value else value.strip())
        except ValueError:
            raise JobError(f"{value!r} is not a date and time (write it like 2026-03-09 09:00)") from None
    else:
        raise JobError("`at` must be a date and time")
    if dt.tzinfo is None:
        if tz is None:
            raise JobError("`at` has no offset, so it needs `tz` (an IANA name such as Europe/Paris)")
        dt = dt.replace(tzinfo=tz)
    return dt.timestamp()


def zone(name: str) -> ZoneInfo:
    try:
        return ZoneInfo(name)
    except (ZoneInfoNotFoundError, ValueError, TypeError):
        raise JobError(f"{name!r} is not a time zone name (an IANA name such as Europe/Paris or Asia/Tokyo)") from None


# the job
@dataclass(frozen=True)
class Job:
    name: str
    kind: str
    room: str
    when: str                     # "calendar" or "at"
    spec: str                     # the calendar line, or the time as written
    tz: str                       # IANA name
    cap: float                    # minutes
    deliver: str
    payload: str                  # the command or the message
    account: str = ""
    at_epoch: float = 0.0
    model: str = ""               # agent jobs: the worker's own model and thinking level; "" the room's
    effort: str = ""

    @property
    def unit(self) -> str:
        return f"{UNIT}{self.name}"

    @property
    def zone(self) -> ZoneInfo:
        return ZoneInfo(self.tz or "UTC")

    def runs_on(self) -> dict[str, str]:
        """The model and thinking level an agent job sets for its worker; {} runs on the room's."""
        return {k: v for k, v in (("model", self.model), ("effort", self.effort)) if v}

    def describe(self) -> str:
        if self.when == "calendar":
            return f"calendar `{self.spec}` {self.tz}"
        return f"one-shot {when_text(self.at_epoch, self.tz)}"

    def planned(self, fired: float) -> float:
        """The time this run was meant for: the one-shot's time; a calendar run's own fire (systemd starts it on its
        second, AccuracySec=1s), so a run caught up after the box was down is planned when it fired."""
        return self.at_epoch if self.when == "at" else fired

    def calendar(self) -> list[str]:
        """OnCalendar= lines: the one-shot's time, or the schedule as written, in the job's zone."""
        if self.when == "at":
            return [datetime.fromtimestamp(self.at_epoch, self.zone).strftime("%Y-%m-%d %H:%M:%S") + f" {self.tz}"]
        return [f"{self.spec} {self.tz}"]


def make_job(name: str, raw: dict[str, Any], now: float | None = None) -> Job:
    """One [jobs.NAME] table checked against KEYS; a JobError says what is wrong."""
    now = time.time() if now is None else now
    if not isinstance(name, str) or not NAME.match(name):
        raise JobError("the name must be lowercase letters, digits and hyphens, starting with a letter or digit, "
                       "at most 60 characters")
    if (bad := sorted(set(raw) - set(KEYS))):
        raise JobError(f"unknown key{'s' if len(bad) > 1 else ''} {', '.join(bad)}; the keys are {', '.join(KEYS)}")
    if (kind := str(raw.get("kind", ""))) not in KINDS:
        raise JobError('`kind` must be "script", "agent" or "note"' + (f", not {kind!r}" if kind else ""))
    if kind == "note" and (extra := [k for k in ("command", "account", "cap", "model", "effort") if k in raw]):
        raise JobError(f"a note runs nothing, so it takes no `{extra[0]}`: its `message` is what its room is told")
    whens = [k for k in ("schedule", "at") if k in raw]
    if len(whens) != 1:
        raise JobError("give exactly one of `schedule` (a systemd calendar line) or `at` (one time)")
    when = {"schedule": "calendar", "at": "at"}[whens[0]]
    tz_name = str(raw.get("tz", "") or "")
    tz = zone(tz_name) if tz_name else None
    if when == "calendar" and tz is None:
        raise JobError("`schedule` needs `tz` (an IANA name such as Europe/Paris), so the hours mean what you mean")
    if not (room := str(raw.get("room", "") or "")):
        raise JobError("`room` is required: the room the output or the relay lands in")
    try:
        cap = float(raw.get("cap", DEFAULT_CAP[kind]))
    except (TypeError, ValueError):
        raise JobError("`cap` must be a number of minutes") from None
    if kind != "note" and not cap > 0:
        raise JobError("`cap` must be above 0 minutes")
    if (deliver := str(raw.get("deliver", "announce"))) not in DELIVER:
        raise JobError('`deliver` must be "announce" or "silent"')
    account, model = str(raw.get("account", "") or ""), str(raw.get("model", "") or "").strip()
    if (effort := str(raw.get("effort", "") or "").strip().lower()) and effort not in EFFORTS:
        raise JobError(f"`effort` must be one of {', '.join(EFFORTS)}, or left out for the room's level")
    if kind == "script":
        if "message" in raw:
            raise JobError("a script job has `command`, not `message`")
        if account:
            raise JobError("a script job runs with no account; `account` is for agent jobs")
        if (extra := [k for k in ("model", "effort") if k in raw]):
            raise JobError(f"a script job runs no model; `{extra[0]}` is for agent jobs")
        payload = str(raw.get("command", "") or "")
        if not payload.strip():
            raise JobError("a script job needs `command`, the shell line to run")
    else:
        if "command" in raw:
            raise JobError("an agent job has `message`, not `command`")
        payload = str(raw.get("message", "") or "")
        if not payload.strip():
            raise JobError("a note needs `message`, the text its room is told" if kind == "note" else
                           "an agent job needs `message`, the brief its worker gets")
    at_epoch, spec = 0.0, ""
    if when == "calendar":
        spec = str(raw["schedule"]).strip()
        if (why := cron_refusal(spec)):
            raise JobError(why)
    else:
        at_epoch = parse_at(raw["at"], tz)
        shown = datetime.fromtimestamp(at_epoch, tz or timezone.utc)
        spec = shown.isoformat(timespec="minutes")
        if tz is None:
            tz_name = "UTC"
        if at_epoch <= now:
            raise JobError(f"`at` {when_text(at_epoch, tz_name)} is in the past")
    return Job(name, kind, room, when, spec, tz_name, cap, deliver, payload, account, at_epoch, model, effort)


def load(path: Path, now: float | None = None) -> tuple[dict[str, Job], dict[str, str]]:
    """Every job in the file, and for each one that cannot be scheduled, why."""
    if not path.is_file():
        return {}, {}
    try:
        data = tomllib.loads(path.read_text())
    except (tomllib.TOMLDecodeError, OSError) as e:
        return {}, {"(file)": f"{path} does not parse: {e}"}
    jobs, errors = {}, {}
    table = data.get("jobs", {})
    if not isinstance(table, dict):
        return {}, {"(file)": f"{path}: [jobs] must be a table of tables"}
    for name, raw in table.items():
        try:
            if not isinstance(raw, dict):
                raise JobError("a job is a table: [jobs.NAME] with its keys below it")
            jobs[str(name)] = make_job(str(name), raw, now)
        except JobError as e:
            errors[str(name)] = str(e)
    return jobs, errors


def when_text(epoch: float | None, tz: str) -> str:
    if epoch is None:
        return "never"
    return datetime.fromtimestamp(epoch, ZoneInfo(tz or "UTC")).strftime("%a %Y-%m-%d %H:%M:%S %Z")


def in_text(epoch: float | None, now: float) -> str:
    if epoch is None:
        return ""
    d = epoch - now
    return f"in {took(d)}" if d >= 0 else f"{took(-d)} ago"


# the file: append a job, remove a job, under a lock
@contextmanager
def locked(path: Path) -> Iterator[None]:
    lock = path.with_name(f".{path.name}.lock")
    with open(lock, "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


def block(name: str, fields: dict[str, Any]) -> str:
    """A [jobs.NAME] table as text, keys in KEYS order."""
    lines = [f"[jobs.{name}]"]
    lines += [f"{k} = {toml_value(fields[k])}" for k in KEYS if k in fields and fields[k] not in ("", None)]
    return "\n".join(lines) + "\n"


def _span(text: str, name: str) -> tuple[int, int] | None:
    """Where [jobs.NAME] sits in the file: its header line through the blank lines before the next
    table; for the last table, the blank lines before it go too, so the file ends cleanly."""
    if not (m := re.search(rf"^\[jobs\.{re.escape(name)}\][ \t]*(#[^\n]*)?\n", text, re.M)):
        return None
    nxt = re.search(r"^\[", text[m.end():], re.M)
    start = m.start()
    if nxt:
        return start, m.end() + nxt.start()
    while start > 0 and text[start - 1] == "\n" and (start < 2 or text[start - 2] == "\n"):
        start -= 1
    return start, len(text)


def add(path: Path, name: str, fields: dict[str, Any], now: float | None = None) -> Job:
    """Append one job to the file (made first, so a bad one never lands); the rest of the file is
    untouched, comments included."""
    job = make_job(name, fields, now)
    with locked(path):
        text = path.read_text() if path.is_file() else ""
        if _span(text, name):
            raise JobError(f"a job named {name!r} is already in the file; remove it first, or pick another name")
        if text and not text.endswith("\n"):
            text += "\n"
        path.write_text(text + ("\n" if text.strip() else "") + block(name, fields))
    return job


def remove(path: Path, name: str) -> bool:
    """Drop [jobs.NAME] from the file; False when it is not there."""
    with locked(path):
        text = path.read_text() if path.is_file() else ""
        if (span := _span(text, name)) is None:
            return False
        path.write_text(text[:span[0]] + text[span[1]:])
    return True


def fields_for(kind: str, when: str, what: str, room: str, tz: str, deliver: str = "announce", cap: float = 0.0,
               account: str = "", model: str = "", effort: str = "") -> dict[str, Any]:
    """The table a `schedule add` writes: `when` is a time (a one-shot) or a systemd calendar line
    (recurring); `what` is the message (agent, note) or the command (script)."""
    w = when.strip()
    out: dict[str, Any] = {"kind": kind, "room": room}
    if re.match(r"^\d{4}-\d{2}-\d{2}", w):
        out["at"] = w
    else:
        out["schedule"] = w
    if tz:
        out["tz"] = tz
    if cap:
        out["cap"] = cap
    if deliver != "announce":
        out["deliver"] = deliver
    if account:
        out["account"] = account
    out.update({k: v for k, v in (("model", model), ("effort", effort)) if v})
    out["command" if kind == "script" else "message"] = what
    return out


def default_tz(room_confs: dict[str, dict[str, Any]], room: str, conf: dict[str, Any]) -> str:
    """The zone a job gets when the call names none: the room's `timezone`, else [memory] timezone
    in yerkd.toml; "" when neither exists (the job is then refused, never put on UTC by accident)."""
    return str(room_confs.get(room, {}).get("timezone") or conf.get("memory", {}).get("timezone") or "")


# the units
@dataclass(frozen=True)
class Env:
    """What a unit needs to run the job the way this process would."""
    python: str
    repo: Path
    private: Path
    state: Path


def env_for(private: Path, state: Path) -> Env:
    return Env(sys.executable, REPO, private.resolve(), state.resolve())


def start_limit(job: Job) -> int:
    """The unit's TimeoutStartSec in seconds: an agent job's runner only hands off, a script runs its cap in the unit."""
    return 120 if job.kind == "agent" else int(job.cap * 60) + 120      # the runner's own cap comes first (L163)


def unit_texts(job: Job, env: Env) -> tuple[str, str]:
    """(timer, service) for the job, byte for byte what sync writes."""
    head = f"{HEADER}{job.name}.\n"
    run = [f"WorkingDirectory={unit_line(str(env.repo))}", f'Environment="PYTHONPATH={unit_line(str(env.repo))}"',
           f'Environment="YERK_PRIVATE={unit_line(str(env.private))}"',
           f'Environment="YERK_STATE={unit_line(str(env.state))}"',
           f"ExecStart={unit_line(env.python, '-P', '-m', 'yerk_ai.jobs', 'run', job.name)}"]
    timer = [head, "[Unit]", f"Description=Yerk AI job {job.name} (timer)", "", "[Timer]"]
    timer += [f"OnCalendar={c}" for c in job.calendar()] + ["Persistent=true"]
    timer += ["AccuracySec=1s", f"Unit={job.unit}.service", "", "[Install]", "WantedBy=timers.target", ""]
    service = [head, "[Unit]", f"Description=Yerk AI job {job.name}", "", "[Service]", "Type=oneshot", *run, f"TimeoutStartSec={start_limit(job)}", ""]
    return "\n".join(timer), "\n".join(service)


class Systemd:
    """systemd's part, as the code relies on it (tests give a fake with files in a folder): unit files in
    the user's systemd folder, `systemctl --user`, `systemd-analyze`. The verbs answer "" or why not."""

    def __init__(self, folder: Path | None = None, stamps: Path | None = None):
        base = Path(os.environ.get("XDG_CONFIG_HOME") or "~/.config").expanduser()
        self.folder = folder or base / "systemd" / "user"
        # where systemd keeps a Persistent timer's last-trigger stamp (written when the timer starts
        # and at each fire); a removed job's stamp goes with it, else a job added later under the same
        # name catches up a boundary from the gap (seen live: every-two re-added 6 s after an even minute)
        self.stamps = stamps or Path(os.environ.get("XDG_DATA_HOME") or "~/.local/share").expanduser() / "systemd" / "timers"

    def path(self, unit: str) -> Path:
        return self.folder / unit

    def read(self, unit: str) -> str | None:
        try:
            return self.path(unit).read_text()
        except OSError:
            return None

    def write(self, unit: str, text: str) -> None:
        self.folder.mkdir(parents=True, exist_ok=True)
        tmp = self.path(unit).with_suffix(self.path(unit).suffix + ".tmp")
        tmp.write_text(text)
        os.replace(tmp, self.path(unit))

    def remove(self, unit: str) -> None:
        for p in ([self.path(unit), self.stamps / f"stamp-{unit}"] if unit.endswith(".timer") else [self.path(unit)]):
            p.unlink(missing_ok=True)

    def ours(self) -> list[str]:                              # job names with a generated unit on disk
        out = []
        for p in sorted([*self.folder.glob(f"{UNIT}*.timer"), *self.folder.glob(f"{UNIT}*.service")]):
            with suppress(OSError):
                if p.read_text().startswith(HEADER):
                    out.append(p.name.removeprefix(UNIT).removesuffix(".timer").removesuffix(".service"))
        return sorted(set(out))

    def reload(self) -> None:
        systemctl("daemon-reload", check="daemon-reload")

    def _unit_cmd(self, *args: str) -> str:
        p = systemctl(*args)
        return "" if p.returncode == 0 else f"systemctl --user {' '.join(args)} exited {p.returncode}: {p.stderr.strip()[:200]}"

    def enable_now(self, timer: str) -> str:
        return self._unit_cmd("enable", "--now", timer)

    def restart(self, timer: str) -> str:
        return self._unit_cmd("restart", timer)

    def disable_now(self, timer: str) -> str:
        return self._unit_cmd("disable", "--now", timer)

    def running(self, unit: str) -> bool:                     # a one-shot service is activating while its run goes
        return systemctl("is-active", unit).stdout.strip() in ("active", "activating")

    def check(self, spec: str) -> str:
        try:
            p = subprocess.run(["systemd-analyze", "calendar", spec], capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            return ""                                          # no systemd-analyze: unchecked, systemd itself decides
        text = p.stdout + p.stderr
        if p.returncode or "Failed to parse" in text:
            return f"systemd does not take {spec!r}: {text.strip().splitlines()[-1][:160] if text.strip() else 'no reason'}"
        return f"{spec!r} never fires again (it is in the past)" if "Next elapse: never" in text else ""

    def timers(self) -> dict[str, dict[str, float | None]]:   # timer unit -> {"next", "last"} (epoch)
        p = systemctl("list-timers", "--all", "--output=json", f"{UNIT}*", check="list-timers")
        return {str(r["unit"]): {"next": (r["next"] / 1e6) if r.get("next") else None,
                                 "last": (r["last"] / 1e6) if r.get("last") else None} for r in json.loads(p.stdout or "[]")}


# the sync
@dataclass
class Plan:
    jobs: dict[str, Job] = field(default_factory=dict)
    errors: dict[str, str] = field(default_factory=dict)
    added: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    failed: dict[str, str] = field(default_factory=dict)       # systemd refused: job -> why


def running_one_shots(path: Path, units: Systemd, errors: dict[str, str]) -> dict[str, Job]:
    """The one-shots `load` refused only for their time having passed whose own service runs: in the file and running.
    Only that run takes one out of the file and then its units; one whose run was cut is refused as any past time is."""
    return {n: j for n, j in load(path, 0)[0].items() if n in errors and j.when == "at" and units.running(f"{j.unit}.service")}


def plan(path: Path, units: Systemd, env: Env, now: float | None = None) -> Plan:
    jobs, errors = load(path, now)
    kept = running_one_shots(path, units, errors)               # kept as they are, never checked for a next fire
    p = Plan(jobs=jobs, errors=errors)
    for name, job in jobs.items():
        for spec in job.calendar():
            if (why := units.check(spec)):
                p.errors[name] = why
                break
        if name in p.errors:
            continue
        timer, service = unit_texts(job, env)
        if (have := (units.read(f"{job.unit}.timer"), units.read(f"{job.unit}.service"))) == (timer or None, service):
            p.unchanged.append(name)
        elif have == (None, None):
            p.added.append(name)
        else:
            p.changed.append(name)
    for name, job in kept.items():
        del p.errors[name]
        p.jobs[name] = job
        p.unchanged.append(name)
    wanted = set(jobs) - set(p.errors)
    p.removed = [n for n in units.ours() if n not in wanted]
    return p


def apply(p: Plan, units: Systemd, env: Env) -> None:
    """Write the changed units, reload once, start the new timers and restart the changed ones,
    disable and remove the dropped ones."""
    for name in p.removed:
        why = units.disable_now(f"{UNIT}{name}.timer")
        if why:
            log.warning("job %s: %s", name, why)
        units.remove(f"{UNIT}{name}.timer")
        units.remove(f"{UNIT}{name}.service")
    for name in p.added + p.changed:
        timer, service = unit_texts(p.jobs[name], env)
        units.write(f"{UNIT}{name}.service", service)
        units.write(f"{UNIT}{name}.timer", timer)
    if p.added or p.changed or p.removed:
        units.reload()
    for name in p.added:
        if (why := units.enable_now(f"{UNIT}{name}.timer")):
            p.failed[name] = why
    for name in p.changed:
        if (why := units.enable_now(f"{UNIT}{name}.timer") or units.restart(f"{UNIT}{name}.timer")):
            p.failed[name] = why


def readback(jobs: dict[str, Job], units: Systemd, now: float | None = None) -> dict[str, dict[str, Any]]:
    """Every job's next and last fire as systemd has them (never from memory)."""
    now = time.time() if now is None else now
    timers = units.timers()
    out: dict[str, dict[str, Any]] = {}
    for name, job in jobs.items():
        t = timers.get(f"{job.unit}.timer")
        out[name] = {"unit": f"{job.unit}.timer", "scheduled": t is not None, "next": t["next"] if t else None,
                     "last": t["last"] if t else None, "tz": job.tz or "UTC"}
    for unit in sorted(set(timers) - {f"{j.unit}.timer" for j in jobs.values()}):
        out[unit.removeprefix(UNIT).removesuffix(".timer")] = {"unit": unit, "scheduled": True, "stray": True,
                                                                   "next": timers[unit]["next"],
                                                                   "last": timers[unit]["last"], "tz": "UTC"}
    return out


def sync(path: Path, units: Systemd, env: Env, now: float | None = None) -> tuple[Plan, dict[str, dict[str, Any]]]:
    p = plan(path, units, env, now)
    apply(p, units, env)
    return p, readback(p.jobs, units, now)


def diff_lines(p: Plan) -> list[str]:
    out = [f"+ {n} (new): {p.jobs[n].describe()}" for n in p.added]
    out += [f"~ {n} (changed): {p.jobs[n].describe()}" for n in p.changed]
    out += [f"- {n} (removed: not in the jobs file)" for n in p.removed]
    if p.unchanged:
        out.append(f"= {len(p.unchanged)} unchanged: {', '.join(p.unchanged)}")
    out += [f"! {n}: cannot be scheduled: {why}" for n, why in sorted(p.errors.items())]
    out += [f"! {n}: systemd refused the timer: {why}" for n, why in sorted(p.failed.items())]
    return out or ["nothing to do: the jobs file is empty and no job timer is on disk"]


def read_lines(back: dict[str, dict[str, Any]], jobs: dict[str, Job], now: float | None = None,
               running: Collection[str] = ()) -> list[str]:
    """One line per job: next fire from systemd, in the job's zone, and the last fire; a one-shot whose run is going
    (`running`) says so in their place."""
    now = time.time() if now is None else now
    out = []
    for name, r in back.items():
        if r.get("stray"):
            out.append(f"timer {r['unit']}: NOT IN THE JOBS FILE (`yerk jobs sync` removes it)")
        elif not r["scheduled"] and name not in running:
            out.append(f"{name}: NOT SCHEDULED (no timer loaded; run `yerk jobs sync`)")
        else:
            nxt = when_text(r["next"], r["tz"]) + (f" ({in_text(r['next'], now)})" if r["next"] else "")
            last = f", last {when_text(r['last'], r['tz'])}" if r["last"] else ", never fired yet"
            head = words.JOB_RUNNING.format(name=name) if name in running else f"{name}: next {nxt}{last}"
            out.append(f"{head}; {jobs[name].describe()}, room {jobs[name].room}, {jobs[name].kind}"
                       + "".join(f", {k} {v}" for k, v in jobs[name].runs_on().items()))
    return out or ["jobs: none"]


def phone(text: str) -> str:
    return text if len(text) <= PHONE - 2 else text[:PHONE - 3].rstrip() + "\N{HORIZONTAL ELLIPSIS}"


def status_lines(path: Path, units: Systemd, now: float | None = None) -> list[str]:
    """`yerk status`: one line per job, state first and phone width: a green dot and how long until
    its next fire (from systemd, never from memory), an orange one for a one-shot whose run is going,
    a white dot for a job with no timer, a red dot for one that cannot be scheduled or a timer with
    no job. The detail (times, zones, why) is `yerk jobs list`. An unreadable timer list is said,
    never shown as empty."""
    now = time.time() if now is None else now
    jobs, errors = load(path, now)
    try:
        kept = running_one_shots(path, units, errors)          # in the file and running, as the sync reads them
        back = readback({**jobs, **kept}, units, now)
    except (OSError, subprocess.SubprocessError, ValueError) as e:
        log.warning("jobs: the timer list could not be read: %s", e)
        return [f"{NOT_DONE} jobs: the timer list could not be read"]
    out = []
    for name, r in back.items():
        if r.get("stray"):
            out.append(phone(f"{NOT_DONE} timer {name}: not in the jobs file"))
        elif name in kept:
            out.append(phone(f"{words.WORKING} " + words.JOB_RUNNING.format(name=name)))
        elif not r["scheduled"]:
            out.append(phone(f"{NOTHING} {name}: not scheduled"))
        elif r["next"]:
            out.append(phone(f"{DONE} {name}: {in_text(r['next'], now)}"))
        else:
            out.append(phone(f"{NOTHING} {name}: no next fire"))
    out += [phone(f"{NOT_DONE} {n}: cannot be scheduled") for n in sorted(errors) if n not in kept]
    return out


# the run: inside the unit
def run_script(job: Job, folder: Path) -> dict[str, Any]:
    """The command under /bin/sh with an account-free environment, the job's cap, stdout and stderr
    to files in the run folder. Returns exit, timed_out, output and the stderr tail. A `yerk` line in it is this install's
    on this install's folders (the unit's YERK_PRIVATE and YERK_STATE), never the fake example layer it falls back to."""
    env = {k: v for k, v in os.environ.items() if k in ENV_KEEP or k in ("YERK_PRIVATE", "YERK_STATE")}
    env.update(TZ=job.tz or "UTC", YERK_JOB=job.name, YERK_JOB_DIR=str(folder), YERK_ROOM=job.room,
               PATH=os.pathsep.join([str(Path(sys.executable).parent), *filter(None, [env.get("PATH")])]))
    t0 = time.time()
    with open(folder / "stdout", "wb") as out, open(folder / "stderr", "wb") as err:
        p = subprocess.Popen(["/bin/sh", "-c", job.payload], cwd=folder, env=env, stdout=out, stderr=err,
                             stdin=subprocess.DEVNULL, start_new_session=True)
        try:
            rc, timed_out = p.wait(timeout=job.cap * 60), False
        except subprocess.TimeoutExpired:
            stop_group(p, grace=10)                    # SIGTERM to its process group, SIGKILL 10 s on
            rc, timed_out = p.wait(), True
    text = (folder / "stdout").read_text(errors="replace")
    tail = (folder / "stderr").read_text(errors="replace").strip().splitlines()
    return {"exit": rc, "timed_out": timed_out, "output": text, "chars": len(text),
            "stderr_tail": tail[-1][:200] if tail else "", "seconds": round(time.time() - t0, 3)}


def post_control(state: Path, payload: dict[str, Any], timeout: float = 120, worker: bool = False, path: str = "control") -> dict[str, Any]:
    """One POST to the running daemon's /control (or /status) under the install's secret (a worker's own
    server: the worker secret, reads only); OSError when no daemon runs on this state folder. yerkd.json
    names the secret files by path, never by value."""
    from .config import read_secret
    from .mcp_server import HEADER
    st = json.loads((state / "yerkd.json").read_text())
    os.kill(int(st["pid"]), 0)
    secret = read_secret(Path(str(st.get("worker_secret_file" if worker else "secret_file") or "/nonexistent")))
    req = urllib.request.Request(f"http://127.0.0.1:{st['port']}/{path}", data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json", HEADER: secret})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return dict(json.loads(r.read()))


def not_listening(e: Exception) -> bool:
    """post_control reached no daemon, so nothing was sent: no yerkd.json, its pid gone or another user's (one left from
    before the box went down), or nothing on its port yet. A daemon that answered, or took the request and was slow, is not."""
    if isinstance(e, urllib.error.URLError) and not isinstance(e, urllib.error.HTTPError) and isinstance(e.reason, OSError):
        e = e.reason
    return isinstance(e, (FileNotFoundError, ProcessLookupError, PermissionError, ConnectionRefusedError))


def run(name: str, private: Path, state: Path, units: Systemd | None = None,
        handoff: Callable[[dict[str, Any]], dict[str, Any]] | None = None, now: float | None = None) -> int:
    """The unit's one step. A script job: ledger the run, run the command, hand the result to the
    daemon for delivery (the ledger says "undelivered" when none runs). An agent job or a note: ask the
    daemon to start the worker or to tell the room. A one-shot is then removed from the file and its units go."""
    units = units or Systemd()
    handoff = handoff or (lambda payload: post_control(state, payload))
    fired = time.time() if now is None else now
    ledger = Ledger(state / "ledger.sqlite")
    jobs, errors = load(private / FILE, now=0)              # now=0: a one-shot that just fired is still a job
    if (job := jobs.get(name)) is None:
        why = errors.get(name, "not in the jobs file")
        ledger.job_run_add(job=name, kind="", room="", unit=f"{UNIT}{name}", planned=fired, fired=fired, ended=fired,
                           exit="not run", result=f"no such job: {why}", delivery="none")
        print(f"job {name}: {why}; `yerk jobs sync` removes its timer", file=sys.stderr)
        return 2
    folder = state / "jobs" / name / time.strftime("%Y%m%d-%H%M%S", time.localtime(fired))
    folder.mkdir(parents=True, exist_ok=True)
    planned = job.planned(fired)
    run_id = ledger.job_run_add(job=name, kind=job.kind, room=job.room, unit=job.unit, planned=planned, fired=fired, folder=str(folder))
    log.info("job %s: run %d fired %.1f s after its time", name, run_id, fired - planned)
    rc = 0
    if job.kind == "script":
        r = run_script(job, folder)
        ended = time.time()
        exit_text = "timed out" if r["timed_out"] else f"exited {r['exit']}"
        ledger.job_run_set(run_id, ended=ended, exit=exit_text, chars=r["chars"])
        payload = {"job": {"action": "result", "name": name, "run": run_id, **{k: r[k] for k in
                   ("exit", "timed_out", "output", "stderr_tail")}}}
        payload["job"]["output"] = str(payload["job"]["output"])[:OUTPUT_MAX + 1]
        rc = 0 if r["exit"] == 0 and not r["timed_out"] else 1
    else:                                       # an agent job, or a note: its text kept in the run's folder, the receipt
        if job.kind == "note":                  # and what a late tell reads (Jobs.reattach)
            (folder / "message").write_text(job.payload)
        payload = {"job": {"action": "fire", "name": name, "run": run_id}}
    deadline = fired + start_limit(job) - RETRY_SPARE        # a one-shot stays in the file while this waits
    while True:
        try:
            out = handoff(payload)
        except (OSError, ValueError) as e:
            if job.kind == "agent" and not_listening(e) and time.time() + RETRY_EVERY < deadline:
                time.sleep(RETRY_EVERY)
                continue
            out = {"ok": False, "error": f"the daemon is not running ({type(e).__name__})"}
        break
    if not out.get("ok"):
        why = str(out.get("error", "the daemon refused it"))
        if job.kind == "script":
            ledger.job_run_set(run_id, result="output" if payload["job"]["output"].strip() else "nothing", delivery=f"undelivered: {why}")
        else:
            ledger.job_run_set(run_id, ended=time.time(), exit="not run", result="did not start", delivery=f"undelivered: {why}")
        print(f"job {name}: {why}", file=sys.stderr)
        rc = rc or 1
    if job.when == "at":
        try:
            remove(private / FILE, name)
            p, _ = sync(private / FILE, units, env_for(private, state))
            log.info("job %s: one-shot fired, removed from the file (%s)", name, "; ".join(diff_lines(p)))
        except (OSError, subprocess.SubprocessError, JobError) as e:
            print(f"job {name}: fired, but could not be removed from the file: {e}", file=sys.stderr)
    return rc


def brief_for(job: Job, run_id: int, fired: float) -> str:
    return (f"You are the scheduled job {job.name} (run {run_id}), fired {when_text(fired, job.tz)}, for the room "
            f"{job.room}.\n"
            "- Your last message is what the room hears, told by the room's own session in its voice: write it for "
            f"the room. If there is nothing worth saying, make your last message exactly {NO_REPLY} and nothing else.\n"
            "- Write that same text as the one line of REPORT.md in your folder; the card shows it.\n\n"
            f"The job:\n\n{job.payload.strip()}\n")


# the schedule tool's three actions: one code path for the tool and for `yerk schedule`
def schedule_add(path: Path, units: Systemd, env: Env, name: str, kind: str, when: str, what: str, room: str, tz: str,
                 deliver: str = "announce", cap: float = 0.0, account: str = "", note_chars: int = NOTE_CHARS,
                 model: str = "", effort: str = "", models: dict[str, str] | None = None) -> dict[str, Any]:
    """Write the job to the file, sync, and answer with the next fire time read back from systemd;
    a job systemd will not schedule is taken out of the file again. A note longer than `note_chars` is refused, and so is
    a `model` off the install's list (`models`, alias = full id), an alias kept as its lowercase name so the job follows the list."""
    name, low, effort = name.strip().lower(), model.strip().lower(), effort.strip().lower()
    model = low if low in (models or {}) else model.strip()
    if kind == "note" and len(what) > note_chars:
        return {"ok": False, "error": words.NOTE_LONG.format(most=note_chars, n=len(what))}
    if kind == "agent" and model and models is not None and model not in models and model not in models.values():
        listed = ", ".join(f"{a} ({words.model_name(m)})" for a, m in models.items())
        return {"ok": False, "error": words.NOT_LISTED.format(model=model, models=listed)}
    if not tz:
        return {"ok": False, "error": f"give `tz` (an IANA name such as Europe/Paris): room {room!r} has no timezone "
                                      "configured, and nothing is put on UTC by accident"}
    try:
        fields = fields_for(kind, when, what, room, tz, deliver, cap, account, model, effort)
        job = add(path, name, fields)
        p, back = sync(path, units, env)
    except JobError as e:
        return {"ok": False, "error": str(e)}
    except (OSError, subprocess.SubprocessError) as e:
        return {"ok": False, "error": f"the sync failed: {e}"}
    r = back.get(name, {})
    if name in p.errors or name in p.failed or not r.get("scheduled"):
        why = p.errors.get(name) or p.failed.get(name) or "systemd shows no timer for it"
        remove(path, name)
        return {"ok": False, "error": f"not scheduled: {why}; the job was taken out of the file again"}
    now = time.time()
    return {"ok": True, "name": name, "unit": r["unit"], "schedule": job.describe(), "room": room, "tz": job.tz,
            "kind": kind, "deliver": job.deliver, **job.runs_on(), "next": r["next"],
            "next_text": f"{when_text(r['next'], job.tz)} ({in_text(r['next'], now)})", "diff": diff_lines(p)}


def schedule_remove(path: Path, units: Systemd, env: Env, name: str) -> dict[str, Any]:
    try:
        had = remove(path, name)
        p, _ = sync(path, units, env)
    except (OSError, subprocess.SubprocessError) as e:
        return {"ok": False, "error": f"the sync failed: {e}"}
    if not had and name not in p.removed:
        return {"ok": False, "error": f"no job {name!r} in the jobs file; jobs: {', '.join(p.jobs) or 'none'}"}
    return {"ok": True, "name": name, "removed": True, "diff": diff_lines(p)}


def schedule_list(path: Path, units: Systemd, only: set[str] | None = None) -> dict[str, Any]:
    """Every job with its next fire time read back; `only`: those jobs alone and no error lines, so a room
    that is not the owner's sees its own notes and never another job's name, room or error."""
    jobs, errors = load(path)
    try:
        kept = running_one_shots(path, units, errors)          # in the file and running, as the sync reads them
        jobs, errors = {**jobs, **kept}, {n: w for n, w in errors.items() if n not in kept}
        back = readback(jobs, units)
    except (OSError, subprocess.SubprocessError, ValueError) as e:
        return {"ok": False, "error": f"the timer list could not be read: {e}"}
    if only is not None:
        back, errors = {n: r for n, r in back.items() if n in only}, {}
    now = time.time()
    rows = [{"name": n, **r, "next_text": when_text(r["next"], r["tz"]) + (f" ({in_text(r['next'], now)})"
                                                                             if r["next"] else ""),
             **({"schedule": jobs[n].describe(), "room": jobs[n].room, "kind": jobs[n].kind,
                 "deliver": jobs[n].deliver, **jobs[n].runs_on()} if n in jobs else {})} for n, r in back.items()]
    lines = read_lines(back, jobs, now, kept) + [f"! {n}: cannot be scheduled: {w}" for n, w in sorted(errors.items())]
    return {"ok": True, "jobs": rows, "errors": errors, "lines": lines}


class Jobs:
    """The daemon's side: the schedule tool, the runner's hand-offs (fire, result), delivery by the
    cron-wrap rule, and the completion hook for job workers."""

    def __init__(self, private: Path, state: Path, ledger: Ledger, conf: dict[str, Any], rooms: dict[str, Any],
                 channels: dict[str, Any], room_confs: dict[str, dict[str, Any]], daemon_conf: dict[str, Any],
                 workers: Workers, units: Systemd | None = None):
        self.private, self.state, self.ledger, self.conf = private, state, ledger, conf
        self.rooms, self.channels, self.room_confs, self.daemon_conf = rooms, channels, room_confs, daemon_conf
        self.workers, self.units = workers, units or Systemd()
        self.path = private / FILE
        self.ops_room = str(conf.get("ops_room", ""))
        self.started = time.time()                      # a note fired before this is the last process's (reattach)
        self.added: dict[str, list[float]] = {}         # a room that is not the owner's: when it added its recent notes
        workers.hooks.append(self.worker_done)

    def env(self) -> Env:
        return env_for(self.private, self.state)

    def jobs(self) -> dict[str, Job]:
        return load(self.path, now=0)[0]

    # the schedule tool and yerk schedule
    async def handle(self, caller: str, req: dict[str, Any]) -> dict[str, Any]:
        if (action := str(req.get("action", ""))) == "add":
            return await asyncio.to_thread(self.add, caller, req)
        if action == "remove":
            return await asyncio.to_thread(self.remove, str(req.get("name", "")))
        if action == "list":
            return await asyncio.to_thread(schedule_list, self.path, self.units)
        if action == "sync":
            return await asyncio.to_thread(self.sync_now)
        if action == "fire":
            return await self.fire(str(req.get("name", "")), int(req.get("run") or 0))
        if action == "result":
            return await self.result(req)
        return {"ok": False, "error": f"no action {action!r}; actions: add, remove, list, sync"}

    async def notes(self, room: str, req: dict[str, Any]) -> dict[str, Any]:
        """The schedule tool in a room that is not the owner's. A note runs nothing as the owner (its room is told
        its text when due), so the room adds, lists and removes its own notes; any other kind runs as the owner, so
        it, and a job for another room, get the line that says what the room can do instead. No answer names
        another job (decision 44): the list is the room's notes alone and the sync's diff is left out. A missing kind
        is a note; the room keeps [jobs] room_notes at most and adds room_note_burst per room_note_minutes (CONF)."""
        action, name = str(req.get("action", "")), str(req.get("name", "")).strip().lower()
        kind, last = str(req.get("kind") or "note"), self.added.get(room, [])
        mine = {n for n, j in self.jobs().items() if (j.kind, j.room) == ("note", room)}
        if action == "list":
            return await asyncio.to_thread(schedule_list, self.path, self.units, mine)
        if action == "remove" and name not in mine:
            return {"ok": False, "error": f"no note {name!r} in this room; its notes: {', '.join(sorted(mine)) or 'none'}"}
        if (add := action == "add" and kind == "note" and str(req.get("room") or room) == room):
            most, every = int(self.conf.get("room_notes", ROOM_NOTES)), float(self.conf.get("room_note_minutes", ROOM_NOTE_MINUTES))
            if len(mine) >= most:
                return {"ok": False, "line": words.NOTES_FULL.format(most=most)}
            burst, now = max(1, int(self.conf.get("room_note_burst", ROOM_NOTE_BURST))), time.time()
            if len(recent := [t for t in last if t > now - every * 60]) >= burst:      # the next fits as the oldest leaves
                what = "one note" if burst == 1 else f"{burst} notes"
                wait = recent[len(recent) - burst] + every * 60 - now
                return {"ok": False, "line": words.NOTES_WAIT.format(what=what, every=f"{every:g}", wait=words.span(wait))}
            self.added[room] = recent + [now]           # taken while the add runs, so two at once cannot both take the last place
        if action == "remove" or add:
            out = await self.handle(room, {**req, "name": name, "kind": kind})
            if add and not out.get("ok"):
                self.added[room] = [t for t in self.added[room] if t != now]   # a refused add gives back its own place only
            return {k: v for k, v in out.items() if k != "diff"}
        log.warning("jobs: room %s is not an owner room; its %s call was refused (its own notes only)", room, action)
        return {"ok": False, "line": words.JOBS_OWNER_ONLY}

    def add(self, caller: str, req: dict[str, Any]) -> dict[str, Any]:
        room = str(req.get("room") or caller) or (next(iter(self.room_confs)) if len(self.room_confs) == 1 else "")
        if room not in self.room_confs:
            return {"ok": False, "error": f"no room {room!r}; rooms: {', '.join(self.room_confs)}"}
        tz = str(req.get("tz") or "") or default_tz(self.room_confs, room, self.daemon_conf)
        out = schedule_add(self.path, self.units, self.env(), str(req.get("name", "")), str(req.get("kind") or "agent"),
                           str(req.get("when", "")), str(req.get("what", "")), room, tz,
                           str(req.get("deliver") or "announce"), float(req.get("cap_minutes") or 0),
                           str(req.get("account") or ""), int(self.conf.get("note_chars", NOTE_CHARS)),
                           str(req.get("model") or ""), str(req.get("effort") or ""), self.workers.models)
        if out["ok"]:
            log.info("job %s: added from %s (%s), next %s", out["name"], caller or "the command line", out["schedule"], out["next_text"])
        return out

    def remove(self, name: str) -> dict[str, Any]:
        out = schedule_remove(self.path, self.units, self.env(), name)
        if out["ok"]:
            log.info("job %s: removed", name)
        return out

    def sync_now(self) -> dict[str, Any]:
        try:
            p, back = sync(self.path, self.units, self.env())
        except (OSError, subprocess.SubprocessError) as e:
            return {"ok": False, "error": str(e)}
        return {"ok": True, "diff": diff_lines(p), "lines": read_lines(back, p.jobs)}

    # the runner's hand-offs
    async def fire(self, name: str, run_id: int) -> dict[str, Any]:
        job = self.jobs().get(name)
        run = self.ledger.job_run_get(run_id)
        if job is None or run is None:
            return {"ok": False, "error": f"no job {name!r}" if job is None else f"no run {run_id}"}
        if job.kind == "note":
            return self.tell(run, job.deliver)
        if job.kind != "agent":
            return {"ok": False, "error": f"job {name} is a {job.kind} job; only agent jobs and notes are fired this way"}
        out = await self.workers.start(job.room, brief_for(job, run_id, float(run["fired"])), account=job.account,
                                       cap_minutes=job.cap, job=name, effort=job.effort,
                                       model=self.workers.models.get(job.model.lower(), job.model))   # an alias, by the list
        if not out.get("ok"):
            self.ledger.job_run_set(run_id, ended=time.time(), exit="not run", result="did not start",
                                    delivery="alert", note=str(out.get("error", "")))
            await self.alert(job, words.job_line(name, "did not start"), run_id)
            return out
        self.ledger.job_run_set(run_id, worker=out["id"])
        return {"ok": True, "worker": out["id"], "run": run_id}

    def tell(self, run: dict[str, Any], deliver: str = "announce") -> dict[str, Any]:
        """A note is due: its room's own session is told the text the runner kept in the run's folder, in a harness
        turn of its own once the room is idle (as a job worker's result is), and says it in its voice. The run reads
        undelivered until that turn ends, so a restart before then has it told at the next start (reattach)."""
        rid, room, mid = int(run["id"]), str(run["room"]), f"note-{run['id']}"
        if deliver == "silent" or room not in self.rooms:
            why = "silent (deliver = silent)" if deliver == "silent" else f"skipped: no room {room!r} in this daemon"
            self.ledger.job_run_set(rid, ended=time.time(), exit="done", result="note", delivery=why)
            return {"ok": True, "run": rid}
        try:
            message = (Path(str(run["folder"])) / "message").read_text().strip()
        except OSError as e:
            return {"ok": False, "error": f"the note's text could not be read: {e}"}
        text = words.NOTE_DUE.format(name=run["job"], message=message, at=words.clock(float(run["planned"])),
                                     under=words.under(self.workers.conf.relay_reply))
        self.ledger.inbound_add(mid, room, "note", HARNESS, len(text))
        self.ledger.job_run_set(rid, delivery=WAITING)

        def then(state: str, ids: list[str], chars: int) -> None:
            self.ledger.job_run_set(rid, ended=time.time(), exit="done", result="note",
                                    delivery="delivered" if state == "answered" else "failed", message_ids=",".join(ids))
        self.workers.ask(room, Inbound(mid, HARNESS, text, cap=self.workers.conf.relay_reply, then=then, alone=True))
        log.info("note %s: run %d asked a turn in %s", run["job"], rid, room)
        return {"ok": True, "run": rid, "inbound": mid}

    async def result(self, req: dict[str, Any]) -> dict[str, Any]:
        """A script's end, delivered by the cron-wrap rule."""
        name, run_id = str(req.get("name", "")), int(req.get("run") or 0)
        job, run = self.jobs().get(name), self.ledger.job_run_get(run_id)
        if run is None:
            return {"ok": False, "error": f"no run {run_id}"}
        room = job.room if job else str(run["room"])
        deliver = job.deliver if job else "announce"
        output, tail = str(req.get("output") or ""), str(req.get("stderr_tail") or "")
        code, timed_out = req.get("exit"), bool(req.get("timed_out"))
        ids: list[str] = []
        if timed_out:                      # the exit code and the stderr tail: the run's note and status --full
            result, delivery = "timed out", "alert"
            self.ledger.job_run_set(run_id, note=f"timed out after {job.cap:g} min" if job else "timed out")
            ids = await self.alert(job, words.job_line(name, "timed out", job.cap * 60 if job else 0.0), run_id, room)
        elif code != 0:
            result, delivery = f"exit {code}", "alert"
            self.ledger.job_run_set(run_id, note=f"exit {code}" + (f": {tail}" if tail else ""))
            ids = await self.alert(job, words.job_line(name, "failed", result="signal" if isinstance(code, int) and
                                                       (code < 0 or code > 128) else "exit-code"), run_id, room)
        elif output.strip():
            result = "output"
            if deliver == "silent":
                delivery = "silent (deliver = silent)"
            else:
                text = output.strip()
                if len(text) > OUTPUT_MAX:
                    text = text[:OUTPUT_MAX].rstrip() + f"\n[cut at {OUTPUT_MAX:,} characters; the whole output is in " \
                                                        "the run's folder]"
                ids = await self.post(room, text, f"job-{run_id}-out")
                delivery = "delivered" if ids else "undelivered: the room could not be posted to"
        else:
            result, delivery = "nothing", "silent (no output)"
        self.ledger.job_run_set(run_id, result=result, delivery=delivery, message_ids=",".join(ids))
        log.info("job %s: run %d %s, %s", name, run_id, result, delivery)
        return {"ok": True, "run": run_id, "result": result, "delivery": delivery, "message_ids": ids}

    async def post(self, room: str, text: str, key: str) -> list[str]:
        if (ch := self.channels.get(room)) is None:
            log.warning("jobs: no channel for room %r; nothing posted", room)
            return []
        try:
            return list(await ch.send_text(room, text, key=key))
        except Exception:
            log.exception("jobs: posting to %s failed", room)
            return []

    async def alert(self, job: Job | None, line: str, run_id: int, room: str = "") -> list[str]:
        """One line to the machine room (rooms.toml role = "machine"), else [jobs] ops_room, else the job's room."""
        machine = [n for n, c in self.room_confs.items() if c.get("role") == "machine" and n in self.channels]
        target = (machine or [self.ops_room if self.ops_room in self.channels else (job.room if job else room)])[0]
        if (ch := self.channels.get(target)) is None:
            log.warning("jobs: no room to alert (%r); %s", target, line)
            return []
        try:
            ids = list(await ch.notify(target, line[:ALERT_MAX]))
        except Exception:
            log.exception("jobs: the alert to %s failed", target)
            return []
        self.ledger.job_run_set(run_id, message_ids=",".join(ids))
        return ids

    # the completion hook for job workers
    async def worker_done(self, row: dict[str, Any], end: dict[str, Any]) -> bool:
        """A job worker's end: silence for NO_REPLY or deliver = silent, an alert when it did not
        finish, else the relay with the worker's last message. True: handled here."""
        if not (name := str(row.get("job") or "")):
            return False
        run = self.ledger.job_run_for_worker(str(row["id"]))
        run_id = int(run["id"]) if run else 0
        job = self.jobs().get(name)
        text = last_message(Path(row["staging"])) or str(end.get("result") or "")
        self.ledger.job_run_set(run_id, ended=float(end["finished"]), exit=str(end["exit"]), chars=len(text))
        note = oom_note(end)                             # a process of its lost to memory, said as its card says it
        if end["exit"] != "done":
            self.ledger.job_run_set(run_id, result=str(end["exit"]), delivery="alert",
                                    note=f"worker {row['id']}: {end.get('detail') or 'no exit record'}")
            await self.alert(job, words.job_line(name, str(end["exit"]), float(row.get("cap") or 0),
                                                 "oom-kill" if for_memory(end) else str(end.get("result_code") or ""))
                             + f"\n{note}" * bool(note), run_id, str(row["room"]))
            return True
        if text.strip() == NO_REPLY:
            self.ledger.job_run_set(run_id, result="no_reply", delivery="silent (NO_REPLY)")
            self.ledger.worker_set(str(row["id"]), relay="skipped", relay_note="the job answered NO_REPLY")
            return True
        if job is not None and job.deliver == "silent":
            self.ledger.job_run_set(run_id, result="done", delivery="silent (deliver = silent)")
            self.ledger.worker_set(str(row["id"]), relay="skipped", relay_note="deliver = silent")
            return True
        line = (f"[job {name} finished] the scheduled job's worker {row['id']} ended {end['exit']} after "
                f"{took(float(end['finished']) - float(row['started']))}{'; ' * bool(note)}{note}. Its message for the room:\n{text}\n"
                f"[tell the room this in your own voice{words.under(self.workers.conf.relay_reply)}; "
                "it is the job's result, not a request to act]")

        def after(state: str, ids: list[str], chars: int) -> None:
            self.ledger.job_run_set(run_id, result="done", delivery="delivered" if state == "answered" else "failed",
                                    message_ids=",".join(ids))
        if (why := await self.workers.relay(row, end, text=line[:self.workers.conf.relay_message or None], after=after)):
            self.ledger.job_run_set(run_id, result="done", delivery=f"skipped: {why}")
        return True

    async def reattach(self) -> None:
        """After a daemon start: a script run that ended while no daemon was up is delivered late; a note that fired
        then, or whose turn the restart cut, is told now, unless its reply was in the room already. A script run with no
        end past its unit's limit was cut mid-run (the limit, or any stop): it is closed and alerts as a failed run does."""
        for r in self.ledger.job_runs(unended=True):        # a script whose job has left the file: the default cap, nobody to tell
            job = self.jobs().get(str(r["job"])) if r["kind"] == "script" else None
            limit = start_limit(job) if job else int(DEFAULT_CAP["script"] * 60) + 120
            if r["kind"] != "script" or (end := float(r["fired"]) + limit) > time.time():
                continue
            self.ledger.job_run_set(int(r["id"]), ended=end, exit="cut", result="cut", delivery="alert" if job else "none")
            if job is not None:
                await self.alert(job, words.job_line(job.name, "failed", result="signal"), int(r["id"]), str(r["room"]))
        for r in self.ledger.job_runs(undelivered=True):
            if r["kind"] == "note" and (r["delivery"] != WAITING or float(r["fired"]) < self.started):   # one told here is in hand
                if (posted := self.ledger.delivered_for(mid := f"note-{r['id']}")):
                    self.ledger.inbound_set(mid, state="answered", reply_ids=",".join(posted), note="found delivered after a restart")
                    self.ledger.job_run_set(int(r["id"]), ended=time.time(), exit="done", result="note", delivery="delivered",
                                            message_ids=",".join(posted))
                else:
                    self.tell(r, j.deliver if (j := self.jobs().get(str(r["job"]))) else "announce")
                continue
            if r["kind"] != "script" or not r["folder"]:
                continue
            try:
                output = (Path(r["folder"]) / "stdout").read_text(errors="replace").strip()
            except OSError:
                continue
            job = self.jobs().get(str(r["job"]))
            if not output or (job is not None and job.deliver == "silent"):
                self.ledger.job_run_set(int(r["id"]), delivery="silent (late; no output or deliver = silent)")
                continue
            text = f"(late: the daemon was not running when job {r['job']} ran at {when_text(r['fired'], job.tz if job else 'UTC')})\n{output[:OUTPUT_MAX]}"
            ids = await self.post(str(r["room"]), text, f"job-{r['id']}-late")
            self.ledger.job_run_set(int(r["id"]), delivery="delivered late" if ids else r["delivery"], message_ids=",".join(ids))


def main(argv: list[str] | None = None) -> int:
    from .config import private_dir, state_dir
    a = sys.argv[1:] if argv is None else argv
    logging.basicConfig(level=logging.INFO, stream=sys.stderr, format="%(asctime)s %(name)s %(message)s")
