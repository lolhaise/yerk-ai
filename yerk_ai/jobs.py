"""Scheduled jobs: what jobs.toml in the private folder lists, run at its times through systemd timers, from one file and one scheduler.

Every job is a table in the private folder's jobs.toml (an example with placeholder values is
examples/private/jobs.toml; KEYS below describes every key in plain words, and `yerk explain jobs`
prints them). `yerk jobs sync` turns the file into one systemd user timer and service per job,
idempotently: an unchanged job is left alone, a changed one is rewritten and restarted, a removed
one is disabled and its files go. It prints the diff, then reads every next fire time back from
systemd and prints that; a job that cannot be scheduled is named with why. `yerk jobs list` is the
read-back alone. The units outlive the daemon, and a timer's Persistent=true fires a run missed
while the box was down, once, on return (DESIGN 7; decisions 15 and 16).

Two schedule kinds: `schedule` (a systemd calendar line, such as `Mon 10:00`) with `tz` (an IANA name);
`at` (one time with tz, removed from the file after it fires). A cron line is refused with the calendar line for it.

Three timed job kinds. A script job runs its `command` inside the unit under an account-free environment
(no account token, no Claude Code variables) with the job's cap, then hands the result to the
running daemon, which delivers by the cron-wrap rule: exit 0 with output posts the output to the
room, exit 0 with nothing posts nothing, a failure or a timeout posts one alert line to the machine
room (rooms.toml role = "machine"), else the ops room (yerkd.toml [jobs] ops_room), else the job's
room. An agent job is a worker (workers.py): the
`message` is its brief, the job's account, cap, model and thinking level apply, its card is in the job's room, and when
it ends its last message is told by the room's own session; a last message of exactly NO_REPLY is
silence. A note runs nothing: when it is due, its room's own session is told `[reminder NAME due]` and
its `message` in a harness turn of its own and says it in its voice (no worker, shell, account or cap).
`deliver = "silent"` keeps a job's output and relay out of the room (the ledger has them);
a failure still alerts. Every run is a row in the ledger's job_runs table: the job, when it was
planned and when it fired, how it ended, what was delivered or why nothing was.

The `schedule` tool (in every room) and `yerk schedule` add a one-shot or a recurring job, remove
one, or list them: they write the jobs file and sync, and answer with the next fire time read back
from systemd. A missing tz is the room's configured one, never UTC by accident. A room that is not the
owner's keeps its own notes and nothing else (Jobs.notes), since every other kind runs as the owner.
"""
