class Systemd:
    """The real one: unit files in the user's systemd folder, `systemctl --user`, `systemd-analyze`."""

    def __init__(self, folder: Path | None = None, stamps: Path | None = None):
        base = Path(os.environ.get("XDG_CONFIG_HOME") or "~/.config").expanduser()
        self.folder = folder or base / "systemd" / "user"
        # where systemd keeps a Persistent timer's last-trigger stamp (written when the timer starts
        # and at each fire); a removed job's stamp goes with it, else a job added later under the same
        # name catches up a boundary from the gap (seen live: every-two re-added 6 s after an even minute)
        self.stamps = stamps or Path(os.environ.get("XDG_DATA_HOME") or "~/.local/share").expanduser() / "systemd" / "timers"

    def path(self, unit: str) -> Path:
        return self.folder / unit

    def read(self, unit: str) -> str | None:
        try:
            return self.path(unit).read_text()
        except OSError:
            return None

    def write(self, unit: str, text: str) -> None:
        self.folder.mkdir(parents=True, exist_ok=True)
        tmp = self.path(unit).with_suffix(self.path(unit).suffix + ".tmp")
        tmp.write_text(text)
        os.replace(tmp, self.path(unit))

    def remove(self, unit: str) -> None:
        for p in ([self.path(unit), self.stamps / f"stamp-{unit}"] if unit.endswith(".timer") else [self.path(unit)]):
            try:
                p.unlink()
            except FileNotFoundError:
                pass

    def ours(self) -> list[str]:
        out = []
        for p in sorted([*self.folder.glob(f"{UNIT}*.timer"), *self.folder.glob(f"{UNIT}*.service")]):
            try:
                if p.read_text().startswith(HEADER):
                    out.append(p.name.removeprefix(UNIT).removesuffix(".timer").removesuffix(".service"))
            except OSError:
                pass
        return sorted(set(out))

    def active(self, unit: str) -> str:
        p = self._ctl("show", "-p", "ActiveState", "--value", unit)
        if p.returncode:
            raise OSError(f"systemctl --user show {unit} exited {p.returncode}: {p.stderr.strip()[:200]}")
        return p.stdout.strip()

    def _ctl(self, *args: str, timeout: float = 60) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True, timeout=timeout)

    def reload(self) -> None:
        p = self._ctl("daemon-reload")
        if p.returncode:
            raise OSError(f"systemctl --user daemon-reload exited {p.returncode}: {p.stderr.strip()[:200]}")

    def _unit_cmd(self, *args: str) -> str:
        p = self._ctl(*args)
        return "" if p.returncode == 0 else f"systemctl --user {' '.join(args)} exited {p.returncode}: " \
                                             f"{p.stderr.strip()[:200]}"

    def enable_now(self, timer: str) -> str:
        return self._unit_cmd("enable", "--now", timer)

    def restart(self, timer: str) -> str:
        return self._unit_cmd("restart", timer)

    def disable_now(self, timer: str) -> str:
        return self._unit_cmd("disable", "--now", timer)

    def check(self, spec: str) -> str:
        try:
            p = subprocess.run(["systemd-analyze", "calendar", spec], capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            return ""                                          # no systemd-analyze: unchecked, systemd itself decides
        text = p.stdout + p.stderr
        if p.returncode or "Failed to parse" in text:
            return f"systemd does not take {spec!r}: {text.strip().splitlines()[-1][:160] if text.strip() else 'no reason'}"
        if "Next elapse: never" in text:
            return f"{spec!r} never fires again (it is in the past)"
        return ""

    def timers(self) -> dict[str, dict[str, float | None]]:
        p = self._ctl("list-timers", "--all", "--output=json", f"{UNIT}*")
        if p.returncode:
            raise OSError(f"systemctl --user list-timers exited {p.returncode}: {p.stderr.strip()[:200]}")
        out: dict[str, dict[str, float | None]] = {}
        for r in json.loads(p.stdout or "[]"):
            out[str(r["unit"])] = {"next": (r["next"] / 1e6) if r.get("next") else None,
                                   "last": (r["last"] / 1e6) if r.get("last") else None}
        return out


# the sync
@dataclass
class Plan:
    jobs: dict[str, Job] = field(default_factory=dict)
    errors: dict[str, str] = field(default_factory=dict)
    added: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    failed: dict[str, str] = field(default_factory=dict)       # systemd refused: job -> why


def plan(path: Path, units: Units, env: Env, now: float | None = None) -> Plan:
    jobs, errors = load(path, now)
    p = Plan(jobs=jobs, errors=errors)
    for name, job in jobs.items():
        for spec in job.calendar():
            why = units.check(spec)
            if why:
                p.errors[name] = why
                break
        if name in p.errors:
            continue
        timer, service = unit_texts(job, env)
        have = (units.read(f"{job.unit}.timer"), units.read(f"{job.unit}.service"))
        if have == (timer or None, service):
            p.unchanged.append(name)
        elif have == (None, None):
            p.added.append(name)
        else:
            p.changed.append(name)
    wanted = set(jobs) - set(p.errors)
    p.removed = [n for n in units.ours() if n not in wanted]
    return p


def apply(p: Plan, units: Units, env: Env) -> None:
    """Write the changed units, reload once, start the new timers and restart the changed ones,
    disable and remove the dropped ones."""
    def lead(name: str) -> str:                          # what is enabled: the timer, or a watcher's service
        return f"{UNIT}{name}.service" if p.jobs[name].kind == "watcher" else f"{UNIT}{name}.timer"
    for name in p.removed + p.changed:                   # removed, or changed to the other kind: its lead goes
        was_timer, gone = units.read(f"{UNIT}{name}.timer") is not None, name in p.removed
        if gone or was_timer != (p.jobs[name].kind != "watcher"):
            why = units.disable_now(f"{UNIT}{name}.timer" if was_timer else f"{UNIT}{name}.service")
            if why:
                log.warning("job %s: %s", name, why)
            units.remove(f"{UNIT}{name}.timer")
            if gone:
                units.remove(f"{UNIT}{name}.service")
    for name in p.added + p.changed:
        timer, service = unit_texts(p.jobs[name], env)
        units.write(f"{UNIT}{name}.service", service)
        if timer:
            units.write(f"{UNIT}{name}.timer", timer)
    if p.added or p.changed or p.removed:
        units.reload()
    for name in p.added:
        why = units.enable_now(lead(name))
        if why:
            p.failed[name] = why
    for name in p.changed:
        why = units.enable_now(lead(name)) or units.restart(lead(name))
        if why:
            p.failed[name] = why


def readback(jobs: dict[str, Job], units: Units, now: float | None = None) -> dict[str, dict[str, Any]]:
    """Every job's next and last fire as systemd has them (never from memory)."""
    now = time.time() if now is None else now
    timers = units.timers()
    out: dict[str, dict[str, Any]] = {}
    for name, job in jobs.items():
        if job.kind == "watcher":                        # no timer: the service's own state
            out[name] = {"unit": f"{job.unit}.service", "scheduled": True, "watcher": True, "next": None,
                         "last": None, "tz": job.tz or "UTC", "active": units.active(f"{job.unit}.service")}
            continue
        t = timers.get(f"{job.unit}.timer")
        out[name] = {"unit": f"{job.unit}.timer", "scheduled": t is not None, "next": t["next"] if t else None,
                     "last": t["last"] if t else None, "tz": job.tz or "UTC"}
    for unit in sorted(set(timers) - {f"{j.unit}.timer" for j in jobs.values()}):
        out[unit.removeprefix(UNIT).removesuffix(".timer")] = {"unit": unit, "scheduled": True, "stray": True,
                                                                   "next": timers[unit]["next"],
                                                                   "last": timers[unit]["last"], "tz": "UTC"}
    return out


def sync(path: Path, units: Units, env: Env, now: float | None = None) -> tuple[Plan, dict[str, dict[str, Any]]]:
    p = plan(path, units, env, now)
    apply(p, units, env)
    return p, readback(p.jobs, units, now)


def diff_lines(p: Plan) -> list[str]:
    out = [f"+ {n} (new): {p.jobs[n].describe()}" for n in p.added]
    out += [f"~ {n} (changed): {p.jobs[n].describe()}" for n in p.changed]
    out += [f"- {n} (removed: not in the jobs file)" for n in p.removed]
    if p.unchanged:
        out.append(f"= {len(p.unchanged)} unchanged: {', '.join(p.unchanged)}")
    out += [f"! {n}: cannot be scheduled: {why}" for n, why in sorted(p.errors.items())]
    out += [f"! {n}: systemd refused the timer: {why}" for n, why in sorted(p.failed.items())]
    return out or ["nothing to do: the jobs file is empty and no job timer is on disk"]


def read_lines(back: dict[str, dict[str, Any]], jobs: dict[str, Job], now: float | None = None) -> list[str]:
    """One line per job: next fire from systemd, in the job's zone, and the last fire."""
    now = time.time() if now is None else now
    out = []
    for name, r in back.items():
        if r.get("stray"):
            out.append(f"timer {r['unit']}: NOT IN THE JOBS FILE (`yerk jobs sync` removes it)")
        elif r.get("watcher"):
            out.append(f"{name}: {'watching' if r['active'] == 'active' else 'NOT RUNNING (' + r['active'] + ')'}; "
                       f"{jobs[name].describe()}, room {jobs[name].room}, unit {r['unit']}")
        elif not r["scheduled"]:
            out.append(f"{name}: NOT SCHEDULED (no timer loaded; run `yerk jobs sync`)")
        else:
            nxt = when_text(r["next"], r["tz"]) + (f" ({in_text(r['next'], now)})" if r["next"] else "")
            last = f", last {when_text(r['last'], r['tz'])}" if r["last"] else ", never fired yet"
            out.append(f"{name}: next {nxt}{last}; {jobs[name].describe()}, room {jobs[name].room}, {jobs[name].kind}")
    return out or ["jobs: none"]


DONE, NOT_DONE, NOTHING = "\N{LARGE GREEN CIRCLE}", "\N{LARGE RED CIRCLE}", "\N{MEDIUM WHITE CIRCLE}"
PHONE = 40                        # a status line, in phone columns (a dot takes two), before it wraps


def phone(text: str) -> str:
    return text if len(text) <= PHONE - 2 else text[:PHONE - 3].rstrip() + "\N{HORIZONTAL ELLIPSIS}"


def status_lines(path: Path, units: Units, now: float | None = None) -> list[str]:
    """`yerk status`: one line per job, state first and phone width: a green dot and how long until
    its next fire (from systemd, never from memory), a white dot for a job with no timer, a red dot
    for one that cannot be scheduled or a timer with no job. The detail (times, zones, why) is
    `yerk jobs list`. An unreadable timer list is said, never shown as empty."""
    now = time.time() if now is None else now
    jobs, errors = load(path, now)
    try:
        back = readback(jobs, units, now)
    except (OSError, subprocess.SubprocessError, ValueError) as e:
        log.warning("jobs: the timer list could not be read: %s", e)
        return [f"{NOT_DONE} jobs: the timer list could not be read"]
    out = []
    for name, r in back.items():
        if r.get("stray"):
            out.append(phone(f"{NOT_DONE} timer {name}: not in the jobs file"))
        elif r.get("watcher"):
            out.append(phone(f"{DONE} {name}: watching" if r["active"] == "active" else f"{NOT_DONE} {name}: not running"))
        elif not r["scheduled"]:
            out.append(phone(f"{NOTHING} {name}: not scheduled"))
        elif r["next"]:
            out.append(phone(f"{DONE} {name}: {in_text(r['next'], now)}"))
        else:
            out.append(phone(f"{NOTHING} {name}: no next fire"))
    out += [phone(f"{NOT_DONE} {n}: cannot be scheduled") for n in sorted(errors)]
    return out


# the run: inside the unit
def last_trigger(units: Units, job: Job) -> float | None:
    try:
        t = units.timers().get(f"{job.unit}.timer")
    except (OSError, subprocess.SubprocessError, ValueError):
        return None
    return t["last"] if t else None


def run_script(job: Job, folder: Path, base: dict[str, str] | None = None) -> dict[str, Any]:
    """The command under /bin/sh with an account-free environment, the job's cap, stdout and stderr
    to files in the run folder. Returns exit, timed_out, output and the stderr tail."""
    env = {k: v for k, v in (os.environ if base is None else base).items() if k in ENV_KEEP}
    env.update(TZ=job.tz or "UTC", YERK_JOB=job.name, YERK_JOB_DIR=str(folder), YERK_ROOM=job.room)
    t0 = time.time()
    with open(folder / "stdout", "wb") as out, open(folder / "stderr", "wb") as err:
        p = subprocess.Popen(["/bin/sh", "-c", job.payload], cwd=folder, env=env, stdout=out, stderr=err,
                             stdin=subprocess.DEVNULL, start_new_session=True)
        timed_out = False
        try:
            rc = p.wait(timeout=job.cap * 60)
        except subprocess.TimeoutExpired:
            timed_out = True
            os.killpg(p.pid, signal.SIGTERM)
            try:
                rc = p.wait(timeout=10)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL)
                rc = p.wait()
    text = (folder / "stdout").read_text(errors="replace")
    tail = (folder / "stderr").read_text(errors="replace").strip().splitlines()
    return {"exit": rc, "timed_out": timed_out, "output": text, "chars": len(text),
            "stderr_tail": tail[-1][:200] if tail else "", "seconds": round(time.time() - t0, 3)}


# the watcher: inside its unit (DESIGN 7; the shape of tools/mail-watch: an output line is a wake-up,
# everything else is a diagnostic in the log; the first start primes)
def matches(job: Job, line: str) -> bool:
    return bool(re.search(job.match, line)) if job.regex else line.startswith(job.match)


def event_key(job: Job, line: str) -> str:
    """A line's identity: the regex's `key` group when it has one, else the whole line."""
    text = line.strip()
    if job.regex and (m := re.search(job.match, text)) and m.groupdict().get("key") is not None:
        text = str(m.group("key"))
    return hashlib.sha1(text.encode()).hexdigest()[:16]


class Watcher:
    """The watcher's unit: the command under /bin/sh (account-free environment, its own process
    group), restarted when it ends (5 s, doubling to 5 min; ten minutes up resets it). Its stdout
    lines that match are events, every other line goes to the unit's log. The very first start
    primes: lines in its first `prime` seconds are recorded as seen, never events. A line whose
    identity was seen before is never an event again, so a restart that prints old lines wakes
    nobody. Matching lines are gathered for `batch` seconds (at most `lines` a wake) into one event,
    ledgered as pending BEFORE the daemon is told; the daemon wakes one turn for it and marks it
    handled when that turn ends clean, and a daemon that is down takes it at its next start."""

    def __init__(self, name: str, private: Path, state: Path,
                 handoff: Callable[[dict[str, Any]], dict[str, Any]] | None = None, popen: Any = subprocess.Popen,
                 clock: Callable[[], float] = time.time, sleep: Callable[[float], None] = time.sleep,
                 diag: Callable[[str], None] | None = None):
        self.name, self.private, self.state = name, private, state
        self.ledger = Ledger(state / "ledger.sqlite")
        self.handoff = handoff or (lambda payload: post_control(state, payload, 30))
        self.popen, self.clock, self.sleep = popen, clock, sleep
        self.diag = diag or (lambda m: print(f"[watch {name}] {m}", file=sys.stderr, flush=True))
        self.stopping = False
        self.proc: Any = None

    def job(self) -> Job | None:
        job = load(self.private / FILE, now=0)[0].get(self.name)
        return job if job is not None and job.kind == "watcher" else None

    def _row(self, job: Job, state: str, got: list[tuple[str, str]]) -> int:
        return self.ledger.watch_add(job=self.name, room=job.room, wake=job.wake, state=state,
                                     lines="\n".join(t for t, _ in got), keys=json.dumps([k for _, k in got]),
                                     received=round(self.clock(), 3), attempts=0)

    def flush(self, job: Job, got: list[tuple[str, str]]) -> int:
        eid = self._row(job, "pending", got)                # persisted before the daemon hears of it
        self.diag(f"event {eid}: {len(got)} line(s)")
        try:
            self.handoff({"job": {"action": "event", "name": self.name, "id": eid}})
        except (OSError, ValueError) as e:
            self.diag(f"event {eid}: the daemon did not answer ({e}); it takes the event at its next start")
        return eid

    def once(self) -> int:
        """One run of the command, to its end; returns its exit code."""
        job = self.job()
        if job is None:
            self.diag("not a watcher in the jobs file; `yerk jobs sync` removes this unit")
            return 2
        rows = self.ledger.watch_events(self.name, limit=5000)
        keys = {k for r in rows for k in json.loads(r["keys"] or "[]")}
        primed = any(r["state"] == "primed" for r in rows)
        env = {k: v for k, v in os.environ.items() if k in ENV_KEEP}
        env.update(TZ=job.tz or "UTC", YERK_JOB=job.name, YERK_ROOM=job.room)
        start = self.clock()
        p = self.popen(["/bin/sh", "-c", job.payload], stdout=subprocess.PIPE, stdin=subprocess.DEVNULL, env=env,
                       start_new_session=True, text=True, bufsize=1)
        self.proc = p
        lines: queue.Queue[str | None] = queue.Queue()

        def read() -> None:
            for x in p.stdout:
                lines.put(x)
            lines.put(None)
        threading.Thread(target=read, name=f"watch-{self.name}", daemon=True).start()
        prime_until = start + job.prime if not primed else None
        absorbed: list[tuple[str, str]] = []
        got: list[tuple[str, str]] = []
        deadline: float | None = None
        while True:
            waits = [t for t in (prime_until, deadline) if t is not None]
            try:
                x = lines.get(timeout=max(0.05, min(waits) - self.clock()) if waits else 1.0)
            except queue.Empty:
                x = ""
            now = self.clock()
            if prime_until is not None and (now >= prime_until or x is None):
                self._row(job, "primed", absorbed)
                self.diag(f"primed: {len(absorbed)} line(s) at the first start are history, not events")
                prime_until = None
            if x is None:
                break
            if x:
                text = x.rstrip("\n")
                if not matches(job, text):
                    self.diag(text)                           # not an event: the unit's log
                elif (key := event_key(job, text)) in keys:
                    self.diag(f"seen before, not an event: {text[:160]}")
                else:
                    keys.add(key)
                    if prime_until is not None:
                        absorbed.append((text, key))
                    else:
                        got.append((text, key))
                        deadline = deadline or now + job.batch
            while got and (len(got) >= job.lines or (deadline is not None and now >= deadline)):
                self.flush(job, got[:job.lines])
                got = got[job.lines:]
                deadline = now + job.batch if got else None
        while got:
            self.flush(job, got[:job.lines])
            got = got[job.lines:]
        return int(p.wait())

    def run(self) -> int:
        def stop(signum: int, frame: Any) -> None:
            self.stopping = True
            if self.proc is not None:
                stop_group(self.proc)
        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGINT, stop)
        backoff = BACKOFF[0]
        while not self.stopping:
            t0 = self.clock()
            rc = self.once()
            if self.stopping:
                break
            ran = self.clock() - t0
            if ran >= STABLE:
                backoff = BACKOFF[0]
            self.diag(f"the command ended (exit {rc}) after {ran:.0f} s; restarting in {backoff:g} s")
            self.sleep(backoff)
            backoff = min(backoff * 2, BACKOFF[1])
        return 0


def post_control(state: Path, payload: dict[str, Any], timeout: float = 120) -> dict[str, Any]:
    """One POST to the running daemon's /control; OSError when no daemon runs on this state folder."""
    st = json.loads((state / "yerkd.json").read_text())
    os.kill(int(st["pid"]), 0)
    req = urllib.request.Request(f"http://127.0.0.1:{st['port']}/control", data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return dict(json.loads(r.read()))


def run(name: str, private: Path, state: Path, units: Units | None = None,
        handoff: Callable[[dict[str, Any]], dict[str, Any]] | None = None, now: float | None = None) -> int:
    """The unit's one step. A script job: ledger the run, run the command, hand the result to the
    daemon for delivery (the ledger says "undelivered" when none runs). An agent job: ask the daemon
    to start the worker. A one-shot is then removed from the file and its units go."""
    units = units or Systemd()
    handoff = handoff or (lambda payload: post_control(state, payload))
    fired = time.time() if now is None else now
    ledger = Ledger(state / "ledger.sqlite")
    jobs, errors = load(private / FILE, now=0)              # now=0: a one-shot that just fired is still a job
    job = jobs.get(name)
    if job is None:
        why = errors.get(name, "not in the jobs file")
        ledger.job_run_add(job=name, kind="", room="", unit=f"{UNIT}{name}", planned=fired, fired=fired, ended=fired,
                           exit="not run", result=f"no such job: {why}", delivery="none")
        print(f"job {name}: {why}; `yerk jobs sync` removes its timer", file=sys.stderr)
        return 2
    folder = state / "jobs" / name / time.strftime("%Y%m%d-%H%M%S", time.localtime(fired))
    folder.mkdir(parents=True, exist_ok=True)
    planned = job.planned(fired, last_trigger(units, job) if job.when == "every" and job.cron is None else None)
    run_id = ledger.job_run_add(job=name, kind=job.kind, room=job.room, unit=job.unit, planned=planned, fired=fired,
                                folder=str(folder))
    log.info("job %s: run %d fired %.1f s after its time", name, run_id, fired - planned)
    rc = 0
    if job.kind == "script":
        r = run_script(job, folder)
        ended = time.time()
        exit_text = "timed out" if r["timed_out"] else f"exited {r['exit']}"
        ledger.job_run_set(run_id, ended=ended, exit=exit_text, chars=r["chars"])
        payload = {"job": {"action": "result", "name": name, "run": run_id, **{k: r[k] for k in
                   ("exit", "timed_out", "output", "stderr_tail")}}}
        payload["job"]["output"] = str(payload["job"]["output"])[:OUTPUT_MAX + 1]
        rc = 0 if r["exit"] == 0 and not r["timed_out"] else 1
    else:
        payload = {"job": {"action": "fire", "name": name, "run": run_id}}
    try:
        out = handoff(payload)
    except (OSError, ValueError) as e:
        out = {"ok": False, "error": f"the daemon is not running ({type(e).__name__})"}
    if not out.get("ok"):
        why = str(out.get("error", "the daemon refused it"))
        if job.kind == "script":
            ledger.job_run_set(run_id, result="output" if payload["job"]["output"].strip() else "nothing",
                               delivery=f"undelivered: {why}")
        else:
            ledger.job_run_set(run_id, ended=time.time(), exit="not run", result="did not start",
                               delivery=f"undelivered: {why}")
        print(f"job {name}: {why}", file=sys.stderr)
        rc = rc or 1
    if job.when == "at":
        try:
            remove(private / FILE, name)
            p, _ = sync(private / FILE, units, env_for(private, state))
            log.info("job %s: one-shot fired, removed from the file (%s)", name, "; ".join(diff_lines(p)))
        except (OSError, subprocess.SubprocessError, JobError) as e:
            print(f"job {name}: fired, but could not be removed from the file: {e}", file=sys.stderr)
    return rc


def last_message(folder: Path) -> str:
    """A worker's last message: the `result` of the last result event in its stdout.jsonl."""
    try:
        lines = (folder / "stdout.jsonl").read_text(errors="replace").splitlines()
    except OSError:
        return ""
    for line in reversed(lines):
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        if isinstance(ev, dict) and ev.get("type") == "result":
            return str(ev.get("result") or "").strip()
    return ""


def brief_for(job: Job, run_id: int, fired: float) -> str:
    return (f"You are the scheduled job {job.name} (run {run_id}), fired {when_text(fired, job.tz)}, for the room "
            f"{job.room}.\n"
            "- Your last message is what the room hears, told by the room's own session in its voice: write it for "
            f"the room. If there is nothing worth saying, make your last message exactly {NO_REPLY} and nothing else.\n"
            "- Write that same text as the one line of REPORT.md in your folder; the card shows it.\n\n"
            f"The job:\n\n{job.payload.strip()}\n")


# the schedule tool's three actions: one code path for the tool and for `yerk schedule`
def schedule_add(path: Path, units: Units, env: Env, name: str, kind: str, when: str, what: str, room: str, tz: str,
                 deliver: str = "announce", cap: float = 0.0, account: str = "") -> dict[str, Any]:
    """Write the job to the file, sync, and answer with the next fire time read back from systemd;
    a job systemd will not schedule is taken out of the file again."""
    name = name.strip().lower()
    if not tz:
        return {"ok": False, "error": f"give `tz` (an IANA name such as Europe/Paris): room {room!r} has no timezone "
                                      "configured, and nothing is put on UTC by accident"}
    try:
        fields = fields_for(kind, when, what, room, tz, deliver, cap, account)
        job = add(path, name, fields)
        p, back = sync(path, units, env)
    except JobError as e:
        return {"ok": False, "error": str(e)}
    except (OSError, subprocess.SubprocessError) as e:
        return {"ok": False, "error": f"the sync failed: {e}"}
    r = back.get(name, {})
    if name in p.errors or name in p.failed or not r.get("scheduled"):
        why = p.errors.get(name) or p.failed.get(name) or "systemd shows no timer for it"
        remove(path, name)
        return {"ok": False, "error": f"not scheduled: {why}; the job was taken out of the file again"}
    now = time.time()
    return {"ok": True, "name": name, "unit": r["unit"], "schedule": job.describe(), "room": room, "tz": job.tz,
            "kind": kind, "deliver": job.deliver, "next": r["next"],
            "next_text": f"{when_text(r['next'], job.tz)} ({in_text(r['next'], now)})", "diff": diff_lines(p)}


def schedule_remove(path: Path, units: Units, env: Env, name: str) -> dict[str, Any]:
    try:
        had = remove(path, name)
        p, _ = sync(path, units, env)
    except (OSError, subprocess.SubprocessError) as e:
        return {"ok": False, "error": f"the sync failed: {e}"}
    if not had and name not in p.removed:
        return {"ok": False, "error": f"no job {name!r} in the jobs file; jobs: {', '.join(p.jobs) or 'none'}"}
    return {"ok": True, "name": name, "removed": True, "diff": diff_lines(p)}


def schedule_list(path: Path, units: Units) -> dict[str, Any]:
    jobs, errors = load(path)
    try:
        back = readback(jobs, units)
    except (OSError, subprocess.SubprocessError, ValueError) as e:
        return {"ok": False, "error": f"the timer list could not be read: {e}"}
    now = time.time()
    rows = [{"name": n, **r, "next_text": when_text(r["next"], r["tz"]) + (f" ({in_text(r['next'], now)})"
                                                                             if r["next"] else ""),
             **({"schedule": jobs[n].describe(), "room": jobs[n].room, "kind": jobs[n].kind,
                 "deliver": jobs[n].deliver} if n in jobs else {})} for n, r in back.items()]
    lines = read_lines(back, jobs, now) + [f"! {n}: cannot be scheduled: {w}" for n, w in sorted(errors.items())]
    return {"ok": True, "jobs": rows, "errors": errors, "lines": lines}


class Jobs:
    """The daemon's side: the schedule tool, the runner's hand-offs (fire, result), delivery by the
    cron-wrap rule, and the completion hook for job workers."""

    def __init__(self, private: Path, state: Path, ledger: Ledger, conf: dict[str, Any], rooms: dict[str, Any],
                 channels: dict[str, Any], room_confs: dict[str, dict[str, Any]], daemon_conf: dict[str, Any],
                 workers: Workers, units: Units | None = None):
        self.private, self.state, self.ledger, self.conf = private, state, ledger, conf
        self.rooms, self.channels, self.room_confs, self.daemon_conf = rooms, channels, room_confs, daemon_conf
        self.workers, self.units = workers, units or Systemd()
        self.path = private / FILE
        self.ops_room = str(conf.get("ops_room", ""))
        self.waking: set[int] = set()                   # watcher events with a turn asked by this process
        self.loop: asyncio.AbstractEventLoop | None = None
        workers.hooks.append(self.worker_done)

    def env(self) -> Env:
        return env_for(self.private, self.state)

    def jobs(self) -> dict[str, Job]:
        return load(self.path, now=0)[0]

    # the schedule tool and yerk schedule
    async def handle(self, caller: str, req: dict[str, Any]) -> dict[str, Any]:
        action = str(req.get("action", ""))
        if action == "add":
            return await asyncio.to_thread(self.add, caller, req)
        if action == "remove":
            return await asyncio.to_thread(self.remove, str(req.get("name", "")))
        if action == "list":
            return await asyncio.to_thread(self.listing)
        if action == "sync":
            return await asyncio.to_thread(self.sync_now)
        if action == "fire":
            return await self.fire(str(req.get("name", "")), int(req.get("run") or 0))
        if action == "result":
            return await self.result(req)
        if action == "event":
            return await self.event(int(req.get("id") or 0))
        return {"ok": False, "error": f"no action {action!r}; actions: add, remove, list, sync"}

    # watcher events: one turn each, handled only after it ends clean, replayed once at most
    async def event(self, event_id: int) -> dict[str, Any]:
        ev = self.ledger.watch_get(event_id)
        if ev is None:
            return {"ok": False, "error": f"no event {event_id}"}
        if ev["state"] != "pending" or event_id in self.waking:
            return {"ok": True, "id": event_id, "state": ev["state"]}
        return await self.wake(ev)

    async def wake(self, ev: dict[str, Any]) -> dict[str, Any]:
        eid, name = int(ev["id"]), str(ev["job"])
        job = self.jobs().get(name)
        lines = str(ev["lines"] or "").splitlines()
        attempt = int(ev["attempts"] or 0) + 1
        self.loop = self.loop or asyncio.get_running_loop()
        self.waking.add(eid)
        self.ledger.watch_set(eid, state="waking", attempts=attempt, woke=round(time.time(), 3))
        room = job.room if job else str(ev["room"])
        if (job.wake if job else str(ev["wake"])) == "worker":
            brief = ((job.ask if job and job.ask else "Look into these lines and say plainly what they mean.")
                     + f"\n\nWatcher {name} saw these lines (event {eid}):\n" + "\n".join(lines))
            out = await self.workers.start(room, brief, account=job.account if job else "",
                                           cap_minutes=job.cap if job else 0.0, job=name, watch=eid)
            if not out.get("ok"):
                await self.ended(eid, "failed", [], note=str(out.get("error", "")))
                return out
            self.ledger.watch_set(eid, worker=str(out["id"]))
            log.info("watcher %s: event %d woke worker %s (attempt %d)", name, eid, out["id"], attempt)
            return {"ok": True, "id": eid, "worker": out["id"]}
        cap = self.workers.conf.relay_reply
        text = words.WATCH_ASK.format(name=name, n=len(lines), s="" if len(lines) == 1 else "s", cap=cap,
                                      what=f"{job.ask} " if job and job.ask else "") + "\n" + "\n".join(lines)
        mid = f"watch-{eid}-{attempt}"
        self.ledger.inbound_add(mid, room, "watcher", HARNESS, len(text))
        self.ledger.watch_set(eid, inbound=mid)
        loop = self.loop

        def then(state: str, ids: list[str], chars: int) -> None:
            loop.call_soon_threadsafe(lambda: self.workers._spawn(self.ended(eid, state, ids)))
        self.workers.ask(room, Inbound(mid, HARNESS, text[:self.workers.conf.relay_message], cap=cap, then=then,
                                       alone=True))
        log.info("watcher %s: event %d asked a turn in %s (attempt %d)", name, eid, room, attempt)
        return {"ok": True, "id": eid, "inbound": mid}

    async def ended(self, eid: int, state: str, ids: list[str], note: str = "", cap: float = 0.0,
                    result: str = "") -> None:
        """The woken turn or worker ended: handled when it ended clean ("answered"); final and silent
        when the owner stopped its worker ("stopped"); else one replay, then failed with one alert line
        naming the end (a worker "timed out" at `cap` seconds, "died" of `result`, a turn "failed")."""
        self.waking.discard(eid)
        ev = self.ledger.watch_get(eid)
        if ev is None:
            return
        if state == "answered":
            self.ledger.watch_set(eid, state="handled", ended=round(time.time(), 3), reply_ids=",".join(ids))
            log.info("watcher %s: event %d handled", ev["job"], eid)
            return
        if state == "stopped":                          # the owner's stop is the event's end: no replay, no alert
            self.ledger.watch_set(eid, state="stopped", ended=round(time.time(), 3),
                                  note=f"attempt {ev['attempts']} stopped by the owner: {note}".strip(": "))
            log.info("watcher %s: event %d stopped by the owner; not replayed", ev["job"], eid)
            return
        if int(ev["attempts"] or 0) < 2:
            self.ledger.watch_set(eid, state="pending", note=f"attempt {ev['attempts']} {state}: {note}".strip(": "))
            log.info("watcher %s: event %d %s; replayed once", ev["job"], eid, state)
            await self.wake(dict(ev, state="pending"))
            return
        self.ledger.watch_set(eid, state="failed", ended=round(time.time(), 3),
                              note=f"attempt {ev['attempts']} {state}: {note}".strip(": "))
        end = state if state in ("timed out", "died", "lost", "did not start") else "failed"
        await self.alert(self.jobs().get(str(ev["job"])), words.job_line(str(ev["job"]), end, cap, result), 0,
                         str(ev["room"]))

    async def events_open(self, restarted: bool = False) -> None:
        """Pending events with no turn asked; after a restart, a turn the old process left: its reply
        found delivered means handled, else the one replay (attempts below 2), else failed."""
        for ev in self.ledger.watch_events(states=("pending", "waking")):
            eid = int(ev["id"])
            if eid in self.waking:
                continue
            if ev["state"] == "waking":
                if not restarted:
                    continue
                if ev["worker"]:
                    w = self.ledger.worker_get(str(ev["worker"]))
                    if w and not w["finished"]:
                        self.waking.add(eid)             # still running: its completion decides
                        continue
                    if w:                                # it ended before its event was settled: its end decides
                        exit_ = str(w.get("exit") or "lost")
                        await self.ended(eid, "answered" if exit_ == "done" else exit_, [], cap=float(w.get("cap") or 0),
                                         note=f"worker {w['id']}: {w.get('exit_detail') or ''}, found after a restart")
                        continue
                posted = self.ledger.delivered_for(str(ev["inbound"])) if ev["inbound"] else []
                if posted:
                    self.ledger.watch_set(eid, state="handled", ended=round(time.time(), 3), reply_ids=",".join(posted),
                                          note="its reply was found delivered after a restart")
                    continue
                if int(ev["attempts"] or 0) >= 2:
                    self.ledger.watch_set(eid, state="failed", note="cut by a restart after its one replay")
                    continue
                self.ledger.watch_set(eid, note="cut by a restart; replayed once")
            await self.wake(ev)

    def add(self, caller: str, req: dict[str, Any]) -> dict[str, Any]:
        room = str(req.get("room") or caller) or (next(iter(self.room_confs)) if len(self.room_confs) == 1 else "")
        if room not in self.room_confs:
            return {"ok": False, "error": f"no room {room!r}; rooms: {', '.join(self.room_confs)}"}
        tz = str(req.get("tz") or "") or default_tz(self.room_confs, room, self.daemon_conf)
        out = schedule_add(self.path, self.units, self.env(), str(req.get("name", "")), str(req.get("kind") or "agent"),
                           str(req.get("when", "")), str(req.get("what", "")), room, tz,
                           str(req.get("deliver") or "announce"), float(req.get("cap_minutes") or 0),
                           str(req.get("account") or ""))
        if out["ok"]:
            log.info("job %s: added from %s (%s), next %s", out["name"], caller or "the command line",
                     out["schedule"], out["next_text"])
        return out

    def remove(self, name: str) -> dict[str, Any]:
        out = schedule_remove(self.path, self.units, self.env(), name)
        if out["ok"]:
            log.info("job %s: removed", name)
        return out

    def listing(self) -> dict[str, Any]:
        return schedule_list(self.path, self.units)

    def sync_now(self) -> dict[str, Any]:
        try:
            p, back = sync(self.path, self.units, self.env())
        except (OSError, subprocess.SubprocessError) as e:
            return {"ok": False, "error": str(e)}
        return {"ok": True, "diff": diff_lines(p), "lines": read_lines(back, p.jobs)}

    # the runner's hand-offs
    async def fire(self, name: str, run_id: int) -> dict[str, Any]:
        job = self.jobs().get(name)
        run = self.ledger.job_run_get(run_id)
        if job is None or run is None:
            return {"ok": False, "error": f"no job {name!r}" if job is None else f"no run {run_id}"}
        if job.kind != "agent":
            return {"ok": False, "error": f"job {name} is a {job.kind} job; only agent jobs are fired this way"}
        out = await self.workers.start(job.room, brief_for(job, run_id, float(run["fired"])), account=job.account,
                                       cap_minutes=job.cap, job=name)
        if not out.get("ok"):
            self.ledger.job_run_set(run_id, ended=time.time(), exit="not run", result="did not start",
                                    delivery="alert", note=str(out.get("error", "")))
            await self.alert(job, words.job_line(name, "did not start"), run_id)
            return out
        self.ledger.job_run_set(run_id, worker=out["id"])
        return {"ok": True, "worker": out["id"], "run": run_id}

    async def result(self, req: dict[str, Any]) -> dict[str, Any]:
        """A script's end, delivered by the cron-wrap rule."""
        name, run_id = str(req.get("name", "")), int(req.get("run") or 0)
        job, run = self.jobs().get(name), self.ledger.job_run_get(run_id)
        if run is None:
            return {"ok": False, "error": f"no run {run_id}"}
        room = job.room if job else str(run["room"])
        deliver = job.deliver if job else "announce"
        output, tail = str(req.get("output") or ""), str(req.get("stderr_tail") or "")
        code, timed_out = req.get("exit"), bool(req.get("timed_out"))
        ids: list[str] = []
        if timed_out:                      # the exit code and the stderr tail: the run's note and status --full
            result, delivery = "timed out", "alert"
            self.ledger.job_run_set(run_id, note=f"timed out after {job.cap:g} min" if job else "timed out")
            ids = await self.alert(job, words.job_line(name, "timed out", job.cap * 60 if job else 0.0), run_id, room)
        elif code != 0:
            result, delivery = f"exit {code}", "alert"
            self.ledger.job_run_set(run_id, note=f"exit {code}" + (f": {tail}" if tail else ""))
            ids = await self.alert(job, words.job_line(name, "failed", result="signal" if isinstance(code, int) and
                                                       (code < 0 or code > 128) else "exit-code"), run_id, room)
        elif output.strip():
            result = "output"
            if deliver == "silent":
                delivery = "silent (deliver = silent)"
            else:
                text = output.strip()
                if len(text) > OUTPUT_MAX:
                    text = text[:OUTPUT_MAX].rstrip() + f"\n[cut at {OUTPUT_MAX:,} characters; the whole output is in " \
                                                        "the run's folder]"
                ids = await self.post(room, text, f"job-{run_id}-out")
                delivery = "delivered" if ids else "undelivered: the room could not be posted to"
        else:
            result, delivery = "nothing", "silent (no output)"
        self.ledger.job_run_set(run_id, result=result, delivery=delivery, message_ids=",".join(ids))
        log.info("job %s: run %d %s, %s", name, run_id, result, delivery)
        return {"ok": True, "run": run_id, "result": result, "delivery": delivery, "message_ids": ids}

    async def post(self, room: str, text: str, key: str) -> list[str]:
        ch = self.channels.get(room)
        if ch is None:
            log.warning("jobs: no channel for room %r; nothing posted", room)
            return []
        try:
            return list(await ch.send_text(room, text, key=key))
        except Exception:
            log.exception("jobs: posting to %s failed", room)
            return []

    async def alert(self, job: Job | None, line: str, run_id: int, room: str = "") -> list[str]:
        """One line to the ops room (yerkd.toml [jobs] ops_room), else the job's room."""
        target = self.ops_room if self.ops_room in self.channels else (job.room if job else room)
        ch = self.channels.get(target)
        if ch is None:
            log.warning("jobs: no room to alert (%r); %s", target, line)
            return []
        try:
            ids = list(await ch.notify(target, line[:ALERT_MAX]))
        except Exception:
            log.exception("jobs: the alert to %s failed", target)
            return []
        self.ledger.job_run_set(run_id, message_ids=",".join(ids))
        return ids

    # the completion hook for job workers
    async def worker_done(self, row: dict[str, Any], end: dict[str, Any]) -> bool:
        """A job worker's end: silence for NO_REPLY or deliver = silent, an alert when it did not
        finish, else the relay with the worker's last message. True: handled here."""
        if row.get("watch"):                            # a watcher's worker: the event's end, then the usual relay
            await self.ended(int(row["watch"]), "answered" if end["exit"] == "done" else str(end["exit"]), [],
                             note=f"worker {row['id']}: {end.get('detail') or ''}", cap=float(row.get("cap") or 0),
                             result=str(end.get("result_code") or ""))
            return False
        name = str(row.get("job") or "")
        if not name:
            return False
        run = self.ledger.job_run_for_worker(str(row["id"]))
        run_id = int(run["id"]) if run else 0
        job = self.jobs().get(name)
        text = last_message(Path(row["staging"])) or str(end.get("result") or "")
        self.ledger.job_run_set(run_id, ended=float(end["finished"]), exit=str(end["exit"]), chars=len(text))
        if end["exit"] != "done":
            self.ledger.job_run_set(run_id, result=str(end["exit"]), delivery="alert",
                                    note=f"worker {row['id']}: {end.get('detail') or 'no exit record'}")
            await self.alert(job, words.job_line(name, str(end["exit"]), float(row.get("cap") or 0),
                                                 str(end.get("result_code") or "")), run_id, str(row["room"]))
            return True
        if text.strip() == NO_REPLY:
            self.ledger.job_run_set(run_id, result="no_reply", delivery="silent (NO_REPLY)")
            self.ledger.worker_set(str(row["id"]), relay="skipped", relay_note="the job answered NO_REPLY")
            return True
        if job is not None and job.deliver == "silent":
            self.ledger.job_run_set(run_id, result="done", delivery="silent (deliver = silent)")
            self.ledger.worker_set(str(row["id"]), relay="skipped", relay_note="deliver = silent")
            return True
        line = (f"[job {name} finished] the scheduled job's worker {row['id']} ended {end['exit']} after "
                f"{took(float(end['finished']) - float(row['started']))}. Its message for the room:\n{text}\n"
                f"[tell the room this in your own voice, under {self.workers.conf.relay_reply:,} characters; "
                "it is the job's result, not a request to act]")

        def after(state: str, ids: list[str], chars: int) -> None:
            self.ledger.job_run_set(run_id, result="done", delivery="delivered" if state == "answered" else "failed",
                                    message_ids=",".join(ids))
        why = await self.workers.relay(row, end, text=line[:self.workers.conf.relay_message], after=after)
        if why:
            self.ledger.job_run_set(run_id, result="done", delivery=f"skipped: {why}")
        return True

    async def reattach(self) -> None:
        """After a daemon start: a script run that ended while no daemon was up is delivered late, and
        every open watcher event gets its turn (or its one replay)."""
        try:
            await self.events_open(restarted=True)
        except Exception:
            log.exception("jobs: the open watcher events could not be taken")
        for r in self.ledger.job_runs(undelivered=True):
            if r["kind"] != "script" or not r["folder"]:
                continue
            try:
                output = (Path(r["folder"]) / "stdout").read_text(errors="replace").strip()
            except OSError:
                continue
            job = self.jobs().get(str(r["job"]))
            if not output or (job is not None and job.deliver == "silent"):
                self.ledger.job_run_set(int(r["id"]), delivery="silent (late; no output or deliver = silent)")
                continue
            text = f"(late: the daemon was not running when job {r['job']} ran at {when_text(r['fired'], job.tz if job else 'UTC')})\n{output[:OUTPUT_MAX]}"
            ids = await self.post(str(r["room"]), text, f"job-{r['id']}-late")
            self.ledger.job_run_set(int(r["id"]), delivery="delivered late" if ids else r["delivery"],
                                    message_ids=",".join(ids))


def main(argv: list[str] | None = None) -> int:
    from .config import private_dir, state_dir
    a = sys.argv[1:] if argv is None else argv
    logging.basicConfig(level=logging.INFO, stream=sys.stderr, format="%(asctime)s %(name)s %(message)s")
    if len(a) == 2 and a[0] == "run":
        return run(a[1], private_dir(), state_dir())
    if len(a) == 2 and a[0] == "watch":
        return Watcher(a[1], private_dir(), state_dir()).run()
    print("usage: python -m yerk_ai.jobs run NAME | watch NAME (the units' own steps)", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
